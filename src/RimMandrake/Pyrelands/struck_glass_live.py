#!/usr/bin/env python3
"""struck_glass_live.py -- live rows for PYRELANDS_STRUCK_GLASS_RITE_BUILD_1 (python.exe, bridge held, a game Playing).

    python.exe src/RimMandrake/Pyrelands/struck_glass_live.py --out src/RimMandrake/Pyrelands/diag/struck_glass_<date>.json

Rows (each PASS / FAIL / UNMEASURED with its evidence):
  A1.defs        RUT_Ritual_StruckGlass, RUT_StruckGlassPattern, RUT_StruckGlassOutcome, RM_StruckGlassRing resolve (get_defs)
  A1.ring        a NEW RM_Pyrelands map (a scratch-world patch re-tiled to RM_Pyrelands, colony founded, map generated by
                 world_tile_map_generate) holds exactly one RM_StruckGlassRing, player-owned (GenStep_StruckGlassRing)
  A2.gate_*      RM_StruckGlass.BlockReason on that ring (the reason the ritual gizmo shows): empty ring -> "not whole";
                 full ring in Clear -> "no lightning storm"; full ring in DryThunderstorm -> null (may start)
NOT covered here (owed to a sitting with the precept on an ideoligion): the ritual gizmo itself and a completed rite's
one strike + letter (ApplyExtraOutcome needs a LordJob_Ritual).

LIES: A1.ring on a map whose genstep found no cell logs '[Pyrelands] Struck Glass: no cell found' and counts 0 -> FAIL, not
UNMEASURED (the genstep has a fallback pass on any dry ground). A gate row reads the C# gate, not the gizmo: a gizmo
that ignored the gate would still pass here.
"""
import argparse
import json
import os
import sys
import time
import types

HERE = os.path.dirname(os.path.abspath(__file__))
UTILS = os.path.join(HERE, "..", "Utils")
for p in (UTILS, os.path.join(UTILS, "modcheck")):
    if p not in sys.path:
        sys.path.insert(0, p)
import biome_site as B          # noqa: E402

RING = "RM_StruckGlassRing"
SG = "RimMandrake.Pyrelands.RM_StruckGlass"
DEFS = ("RitualPatternDef/RUT_StruckGlassPattern", "PreceptDef/RUT_Ritual_StruckGlass",
        "RitualOutcomeEffectDef/RUT_StruckGlassOutcome", "ThingDef/RM_StruckGlassRing")
SPEC = types.SimpleNamespace(BIOME="RM_Pyrelands", LAT_MAX=45.0,
                             TILE={"temperature": 30.0, "rainfall": 150.0, "elevation": 120.0, "hilliness": "Flat",
                                   "swampiness": 0.0})
MAP_SIZE = 200


def row(rows, rid, status, evidence):
    rows.append({"id": rid, "status": status, "evidence": evidence})
    print("[struckglass] %s %s %s" % (rid, status, str(evidence)[:300]), flush=True)


def gate(s, ring_id):
    r = s.call("jawa/static_call", type=SG, method="BlockReason", args=ring_id) or {}
    if r.get("success") is False:
        return None, r
    return r.get("result"), r


def run(s, work_dir, reread=None):
    """reread: the id of a map THIS script generated earlier in the session -> re-read A1 only (no second map)."""
    rows = []
    # HARNESS 2026-10-21: get_defs does not split a comma list (it looked up the whole string as one name): one call per def
    found, missing = [], []
    for dn in DEFS:
        d = s.call("jawa/get_defs", defs=dn, fields="defName", limit=2) or {}
        (found if d.get("foundCount") and not d.get("notFound") else missing).append(dn)
    row(rows, "A1.defs", "PASS" if not missing else "FAIL", {"found": found, "notFound": missing})

    NS = B.pyre()
    if reread is None:
        colony_tile = (s.call("jawa/map_info") or {}).get("tile")
        pick = B.choose_tile(s, SPEC, os.path.join(work_dir, "struckglass_site"), colony_tile)
        B.retile(s, SPEC, pick["patch"])
        NS.strip_mutators(s, pick["centre"])
        g = NS.generate(s, pick["centre"], MAP_SIZE)
        home = NS.home(s, g["mapId"], 3)
    else:
        s.call("jawa/set_current_map", mapId=reread)
        pick, g = {"centre": None}, {"mapId": reread}
        cols = (s.call("rimworld/list_colonists", currentMapOnly=True) or {}).get("colonists") or []
        home = {"colonists": [c.get("id") or c.get("thingId") for c in cols], "previousMapId": None}
    mi = s.call("jawa/map_info") or {}
    if mi.get("mapBiome") != SPEC.BIOME:
        row(rows, "A1.ring", "UNMEASURED", "the generated map's biome is %r, not %s" % (mi.get("mapBiome"), SPEC.BIOME))
        return rows
    lt = s.call("jawa/list_things", defName=RING, limit=20) or {}
    rings = lt.get("things") or []
    ev = {"tile": pick["centre"], "mapId": g["mapId"], "rings": [(r.get("id"), r.get("x"), r.get("z"),
                                                                 r.get("factionName") or r.get("faction")) for r in rings]}
    if lt.get("success") is False or not isinstance(lt.get("things"), list):
        row(rows, "A1.ring", "UNMEASURED", "list_things unreadable: %s" % str(lt)[:200])
        return rows
    # HARNESS 2026-10-21: the player faction reads by its NAME ("Northstar Cauldron" on the scratch world), so compare with
    # a colonist's own faction rather than looking for the word "player"
    pl = s.call("jawa/list_pawns", limit=50, faction="player") or {}
    mine = set(p.get("factionName") for p in pl.get("pawns") or [] if p.get("isPlayer") and p.get("factionName"))
    ev["playerFaction"] = sorted(str(x) for x in mine)
    owned = bool(mine) and all((r.get("factionName") or r.get("faction")) in mine for r in rings)
    row(rows, "A1.ring", "PASS" if len(rings) == 1 and owned else "FAIL", ev)
    if len(rings) != 1 or reread is not None:
        return rows
    rid = rings[0]["id"]

    s.call("jawa/weather_set", weather="Clear", lockWeather=True)
    why, r = gate(s, rid)
    row(rows, "A2.gate_empty_ring", "UNMEASURED" if r.get("success") is False else
        ("PASS" if why and "not whole" in str(why) else "FAIL"), {"reason": why})
    f = s.call("jawa/thing_refuel", thingId=rid, amount=25) or {}
    why, r = gate(s, rid)
    row(rows, "A2.gate_full_no_storm", "UNMEASURED" if r.get("success") is False or not f.get("hasFuel") else
        ("PASS" if why and "no lightning storm" in str(why) else "FAIL"), {"refuel": str(f)[:200], "reason": why})
    s.call("jawa/weather_set", weather="DryThunderstorm", lockWeather=True)
    why, r = gate(s, rid)
    row(rows, "A2.gate_full_in_storm", "UNMEASURED" if r.get("success") is False else
        ("PASS" if why in (None, "null", "") else "FAIL"), {"reason": why})
    s.call("jawa/weather_set", weather="Clear", lockWeather=False)
    rows.append({"id": "home", "evidence": {k: home[k] for k in ("colonists", "previousMapId")}})
    return rows


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    ap.add_argument("--reread-map", type=int, help="re-read A1 on a map this script already generated (no new map)")
    a = ap.parse_args()
    from northstar_driver.session import FastSession
    s = FastSession(strict=False)
    with s:
        rows = run(s, os.path.dirname(os.path.abspath(a.out)), a.reread_map)
    with open(a.out, "w") as fh:
        json.dump({"utc": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()), "rows": rows}, fh, indent=1)
    bad = [r for r in rows if r.get("status") not in (None, "PASS")]
    print("struck glass: %d rows, not PASS: %s" % (len([r for r in rows if r.get("status")]), [r["id"] for r in bad]))
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
