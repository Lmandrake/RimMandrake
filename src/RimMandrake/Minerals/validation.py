"""validation.py -- functional script for RimMandrake: Minerals (mandrake.rm.minerals). MINERAL_POLICY_CODE_STARTUP_ZEROING (R2 of
MINERALS_WHERE_THEY_BELONG_1; design/RimMandrake/mineral_abundance_registry_design_2026-10-03.md §6.2, §7).

THE MOD: Defs/RM_MineralRegistry.xml (generated by src/RimMandrake/Utils/gen_mineral_registry.py from the registry CSV) loads as
RM_MineralRegistryDef; the static RM_MineralPolicy zeroes, at startup and again on every Game.FinalizeInit, the scatter/deep weight of
every def the registry disables or that has no source anywhere; unregistered ores keep their weights unless the player suppresses them.
Walk: design/validation_walks/RimMandrake/Minerals.md.

OFFLINE: `python3 validation.py` -> static checks (`STATIC: PASS (0 findings)`); the kernel's behaviour over the shipped registry and the
real def weights is src/RimMandrake/Utils/selftest_minerals.py.
LIVE (owed; never run): the suite below, through modcheck. It reads state with the jawa/static_call hooks
RM_MineralPolicyProof.ProofState / ProofApply and jawa/mod_settings_field. A component that cannot ask records UNMEASURED.
"""
import os
import re
import sys
import xml.etree.ElementTree as ET

HERE = os.path.dirname(os.path.abspath(__file__))
NS = "RimMandrake.Minerals."
SETTINGS_TYPE = NS + "RM_MineralsSettings"
PROOF_TYPE = NS + "RM_MineralPolicyProof"
REGISTRY_CLASS = NS + "RM_MineralRegistryDef"
SETTINGS = ["enabled", "suppressUnregistered", "coreSampleNonLocal", "veinMultiplier", "deepMultiplier", "quarryMultiplier",
            "salvageMultiplier", "tradeMultiplier"]
DEFAULTS = {"enabled": True, "suppressUnregistered": False, "coreSampleNonLocal": False, "veinMultiplier": 1.0,
            "deepMultiplier": 1.0, "quarryMultiplier": 1.0, "salvageMultiplier": 1.0, "tradeMultiplier": 1.0}
ALT = {"enabled": False, "suppressUnregistered": True, "coreSampleNonLocal": True, "veinMultiplier": 0.5, "deepMultiplier": 2.0,
       "quarryMultiplier": 1.5, "salvageMultiplier": 0.25, "tradeMultiplier": 2.5}
UNITS = {"EPM", "EPM/yr", "UPY", "deep share", "—"}     # == mineral_registry_check.UNITS
# owner 2026-09-25: "fix that absurd thing in Vanilla where components and plasteel can be mined from rock"
MUST_ZERO = ["MineableComponentsIndustrial", "MineablePlasteel"]
# the Steel registry row is GUESS (not emitted), so steel is unregistered and must keep vanilla weights (scatter 1, deep 4)
STEEL = {"MineableSteel": (1.0, None), "Steel": (None, 4.0)}


def _strip_cs(text):
    return re.sub(r"//[^\n]*", "", text)


def _read(*parts):
    with open(os.path.join(HERE, *parts), encoding="utf-8") as f:
        return f.read()


def static_checks():
    bad = []
    mod = _read("Source", "RM_MineralsMod.cs")
    body = mod.split("class RM_MineralsSettings", 1)[1].split("public override void ExposeData", 1)[0]
    fields = re.findall(r"public\s+static\s+(?:bool|float|int)\s+(\w+)\s*=", _strip_cs(body))
    if fields != SETTINGS:
        bad.append("settings fields changed: %s (update SETTINGS, DEFAULTS, the walk and suite.toggles)" % fields)
    expose = mod.split("public override void ExposeData", 1)[1].split("public static void ResetAll", 1)[0]
    draw = mod.split("public static void Draw", 1)[1]
    for n in fields:
        if '"%s"' % n not in expose:
            bad.append("setting %s is not scribed" % n)
        if "ref %s" % n not in draw:
            bad.append("setting %s has no control in Draw" % n)
    if "Scribe_Collections.Look(ref overrides" not in expose:
        bad.append("per-biome overrides are not scribed")
    for needle in ("PatchApplier.BeforeExpose", "PatchApplier.AfterExpose", "PatchApplier.DrawNotice", "RM_MineralPolicy.Apply("):
        if needle not in mod:
            bad.append("RM_MineralsMod.cs lacks %s" % needle)

    pol = _read("Source", "RM_MineralPolicy.cs")
    for needle in ("[StaticConstructorOnStartup]", "[HarmonyPatch(typeof(Game), nameof(Game.FinalizeInit))]", "PatchFeature(",
                   "RM_MineralPolicyKernel.Readopt(", "RM_MineralPolicyKernel.Decide(", "public static string ProofState(string defs)",
                   "public static string ProofApply(string why)"):
        if needle not in pol:
            bad.append("RM_MineralPolicy.cs lacks %s" % needle)

    proj = _read("Source", "RimMandrake_Minerals.csproj")
    classes = set()
    for dp, _, files in os.walk(os.path.join(HERE, "Source")):
        if "SelfTest" in dp or os.sep + "obj" in dp or os.sep + "bin" in dp:
            continue
        for fn in files:
            if fn.endswith(".cs"):
                if fn not in proj:
                    bad.append("%s is not in the csproj" % fn)
                classes |= set(re.findall(r"\bclass (\w+)", _read(os.path.relpath(os.path.join(dp, fn), HERE))))
    for c in ("RM_MineralRegistryDef", "RM_MineralBiomeCell", "RM_MineralsSettings", "RM_MineralPolicyProof"):
        if c not in classes:
            bad.append("sanity: the class scan cannot see %s" % c)

    known = set(re.findall(r'"([^"]+)"', _read("Source", "RM_MineralRegistryDef.cs").split("KnownUnits", 1)[1].split("}", 1)[0]))
    if known != UNITS:
        bad.append("RM_MineralRegistryDef.KnownUnits %s != mineral_registry_check units %s" % (sorted(known), sorted(UNITS)))

    root = ET.parse(os.path.join(HERE, "Defs", "RM_MineralRegistry.xml")).getroot()
    defs = list(root)
    if len(defs) < 20:
        bad.append("registry has %d defs (sanity probe: R1 emitted 31)" % len(defs))
    ids, names = [], []
    for d in defs:
        if d.tag != REGISTRY_CLASS:
            bad.append("registry element <%s> is not %s" % (d.tag, REGISTRY_CLASS))
            continue
        names.append(d.findtext("defName"))
        ids.append(d.findtext("materialId"))
        if (d.findtext("unit") or "") not in UNITS:
            bad.append("%s: unit %r unknown" % (names[-1], d.findtext("unit")))
        for c in d.findall("biomes/li"):
            if not c.findtext("biome") or (c.find("value") is None) == (c.find("token") is None):
                bad.append("%s: a biome cell needs a biome and exactly one of value/token" % names[-1])
    for label, xs in (("materialId", ids), ("defName", names)):
        dup = sorted({x for x in xs if xs.count(x) > 1})
        if dup:
            bad.append("duplicate %s: %s" % (label, dup))
    zero = {li.text for d in defs for li in d.findall("zeroProducers/li") + d.findall("retiredItems/li")}
    for m in MUST_ZERO:
        if m not in zero:
            bad.append("%s is no longer a zero producer in the registry (owner 2026-09-25 ruling)" % m)
    if "steel" in ids:
        bad.append("a steel row is emitted now: re-check STEEL expectations (unregistered-by-default) before shipping")

    about = ET.parse(os.path.join(HERE, "About", "About.xml")).getroot()
    if about.findtext("packageId") != "mandrake.rm.minerals":
        bad.append("About packageId is %r" % about.findtext("packageId"))
    if not os.path.isfile(os.path.join(HERE, "Source", "SelfTest", "mineral_defs.tsv")):
        bad.append("selftest fixture mineral_defs.tsv missing")
    return bad


def _parse_state(text):
    """'rev=3;rows=31;...;MineableSteel=1/0/unregistered' -> dict of str."""
    out = {}
    for part in (text or "").split(";"):
        if "=" in part:
            k, v = part.split("=", 1)
            out[k] = v
    return out


def _build_suite():
    from modcheck import Suite, ExpectationFailed
    suite = Suite("Minerals")
    suite.toggles = list(SETTINGS)

    def _unmeasured(t, why):
        t.upstream_reason = "UNMEASURED: " + why
        t.upstream_failed = True

    def _live(t):
        return t.session is not None

    def _get(t, field):
        return ((t.bridge_call("jawa/mod_settings_field", typeName=SETTINGS_TYPE, action="get", field=field) or {}).get("value"))

    def _set(t, field, value):
        t.bridge_call("jawa/mod_settings_field", typeName=SETTINGS_TYPE, action="set", field=field, value=str(value))

    def _restore(t, field):
        if t.session is not None:
            try:
                t.session.call("jawa/mod_settings_field", typeName=SETTINGS_TYPE, action="set", field=field,
                               value=str(DEFAULTS[field]))
                t.session.call("jawa/static_call", type=PROOF_TYPE, method="ProofApply", args="restore " + field)
            except Exception as ex:
                print("[minerals] RESTORE FAILED %s: %s" % (field, ex), file=sys.stderr, flush=True)

    def _same(got, want):
        if isinstance(want, bool):
            return str(got).strip().lower() == str(want).lower()
        try:
            return abs(float(got) - float(want)) < 1e-6
        except (TypeError, ValueError):
            return False

    def _call(t, method, args):
        r = t.bridge_call("jawa/static_call", type=PROOF_TYPE, method=method, args=args)
        if not isinstance(r, dict) or r.get("success") is False:
            raise ExpectationFailed("static_call %s could not run: %r" % (method, r))
        return _parse_state(str(r.get("result", "")))

    def _weights(s, name):
        v = s.get(name)
        if v is None or v == "missing":
            return None
        sc, dp, role = v.split("/", 2)
        return float(sc), float(dp), role

    probe = ";".join(MUST_ZERO + list(STEEL) + ["Plasteel", "RM_NoSuchMineral_control"])

    # Registered FIRST (chains run in registration order): read the last apply reason before any ProofApply - the toggles chain
    # and every _restore re-apply and overwrite it. Its own chain, so its UNMEASURED latch cannot blank the defs_resolve rows.
    @suite.chain("reassert")
    def reassert(t):
        with t.component("reassert_on_game_init", beyond_toggle=True):
            if not _live(t):
                return
            reason = _call(t, "ProofState", "").get("reason", "")
            if reason.startswith("proof:") or reason == "settings changed" or reason.startswith("surface placer registered"):
                _unmeasured(t, "last apply was %r, after the game started; FinalizeInit is proven on a fresh load only" % reason)
            elif reason != "Game.FinalizeInit":
                raise ExpectationFailed("last apply reason %r in a running game: the FinalizeInit re-assert never ran" % reason)

    @suite.chain("defs_resolve")
    def defs_resolve(t):
        with t.component("registry_loaded", beyond_toggle=True):
            if not _live(t):
                return
            s = _call(t, "ProofState", "")
            if int(s.get("rows", 0)) < 20:
                raise ExpectationFailed("the policy sees %r registry rows (expected >= 20: defs did not load)" % s.get("rows"))
            if int(s.get("rev", 0)) < 1:
                raise ExpectationFailed("the startup apply never ran (rev %r)" % s.get("rev"))
        with t.component("probe_can_say_absent", beyond_toggle=True):
            if not _live(t):
                return
            s = _call(t, "ProofState", "RM_NoSuchMineral_control")
            if s.get("RM_NoSuchMineral_control") != "missing":
                raise ExpectationFailed("a def that does not exist did not read missing: %r" % s)

    @suite.chain("zeroing")
    def zeroing(t):
        with t.component("components_and_plasteel_zeroed", toggle="enabled"):
            if not _live(t):
                return
            s = _call(t, "ProofState", probe)
            for n in MUST_ZERO:
                w = _weights(s, n)
                if w is None:
                    _unmeasured(t, "%s is not loaded on this list" % n)
                    return
                if w[0] != 0.0:
                    raise ExpectationFailed("%s still scatters at %r with the policy on" % (n, w[0]))
        with t.component("unregistered_steel_kept", beyond_toggle=True):
            if not _live(t):
                return
            s = _call(t, "ProofState", probe)
            for n, (sc, dp) in STEEL.items():
                w = _weights(s, n)
                if w is None:
                    raise ExpectationFailed("%s missing from the running game" % n)
                if w[2] != "unregistered" or (sc is not None and w[0] != sc) or (dp is not None and w[1] != dp):
                    raise ExpectationFailed("%s must keep vanilla weights while unregistered: %r" % (n, w))

    @suite.chain("toggles")
    def toggles(t):
        with t.component("master_off_restores", toggle="enabled"):
            if not _live(t):
                return
            try:
                _set(t, "enabled", False)
                s = _call(t, "ProofApply", "master off")
                for n in MUST_ZERO:
                    w = _weights(s, n) or _weights(_call(t, "ProofState", n), n)
                    if w is None:
                        _unmeasured(t, "%s is not loaded on this list" % n)
                        return
                    if w[0] <= 0.0:
                        raise ExpectationFailed("master off: %s did not get its original scatter back (%r)" % (n, w))
            finally:
                _restore(t, "enabled")
            w = _weights(_call(t, "ProofState", MUST_ZERO[0]), MUST_ZERO[0])
            if w is None or w[0] != 0.0:
                raise ExpectationFailed("master back on: %s not zeroed again (%r)" % (MUST_ZERO[0], w))
        with t.component("suppress_unregistered_zeroes_steel", toggle="suppressUnregistered"):
            if not _live(t):
                return
            try:
                _set(t, "suppressUnregistered", True)
                _call(t, "ProofApply", "suppress on")
                w = _weights(_call(t, "ProofState", "MineableSteel"), "MineableSteel")
                if w is None or w[0] != 0.0:
                    raise ExpectationFailed("suppression on: MineableSteel kept scatter (%r)" % (w,))
            finally:
                _restore(t, "suppressUnregistered")
            w = _weights(_call(t, "ProofState", "MineableSteel"), "MineableSteel")
            if w is None or w[0] != 1.0:
                raise ExpectationFailed("suppression off: MineableSteel did not get scatter 1 back (%r)" % (w,))

    @suite.chain("settings_roundtrip")
    def settings_roundtrip(t):
        for field in SETTINGS:
            with t.component("%s_roundtrip" % field, beyond_toggle=True):
                if not _live(t):
                    continue
                try:
                    if not _same(_get(t, field), DEFAULTS[field]):
                        raise ExpectationFailed("%s does not read its default %r: %r" % (field, DEFAULTS[field], _get(t, field)))
                    _set(t, field, ALT[field])
                    if not _same(_get(t, field), ALT[field]):
                        raise ExpectationFailed("%s write did not take" % field)
                finally:
                    _restore(t, field)
                if not _same(_get(t, field), DEFAULTS[field]):
                    raise ExpectationFailed("%s did not restore" % field)
        with t.component("settings_ui_draws", beyond_toggle=True):
            if not _live(t):
                return
            _unmeasured(t, "the settings window (biome picker, per-material fields) needs eyes: open Mod Settings > RimMandrake: "
                           "Minerals, pick a biome, edit one value, reopen, see it starred")

    return suite


try:
    suite = _build_suite()
except ImportError:      # outside the modcheck path: the static check needs no game
    suite = None

if __name__ == "__main__":
    problems = static_checks()
    print("STATIC: %s" % ("PASS (0 findings)" if not problems else "FAIL"))
    for p in problems:
        print("  - " + p)
    sys.exit(1 if problems else 0)
