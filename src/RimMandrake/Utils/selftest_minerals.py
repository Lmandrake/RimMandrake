#!/usr/bin/env python3
"""MINERAL_POLICY_CODE_STARTUP_ZEROING L0 selftest of the mineral policy kernel (src/RimMandrake/Minerals/Source/Kernel/), no game.

The C# SelfTest (Source/SelfTest/Program.cs) compiles the PRODUCTION kernel alone and runs it over:
  - the shipped registry, src/RimMandrake/Minerals/Defs/RM_MineralRegistry.xml (generated by gen_mineral_registry.py);
  - DeepDrill's shipped home table (the deep channel must agree with it);
  - Source/SelfTest/mineral_defs.tsv: every ThingDef of the def dump that bears scatter/deep weight or is a mineable, with its
    real values. The fixture is committed so the test is dump-free and deterministic; refresh it with --refresh-fixture.
Built through winbuild.stage_build (dotnet.exe is Windows-native), then run.

    python3 src/RimMandrake/Utils/selftest_minerals.py [--refresh-fixture [--dump P]]
"""
import os
import re
import sqlite3
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(os.path.dirname(HERE)))
sys.path.insert(0, HERE)
import winbuild  # noqa: E402

MOD = os.path.join(REPO, "src", "RimMandrake", "Minerals")
SELFTEST = os.path.join(MOD, "Source", "SelfTest")
CSPROJ = os.path.join(SELFTEST, "RimMandrakeMinerals.SelfTest.csproj")
FIXTURE = os.path.join(SELFTEST, "mineral_defs.tsv")
DEEP_DEFS = os.path.join(REPO, "src", "RimMandrake", "DeepDrill", "Defs")
DUMP_DEFAULT = ("/mnt/c/Users/Mandrake/AppData/LocalLow/Ludeon Studios/"
                "RimWorld by Ludeon Studios/DefDump/defs.sqlite")


def _num(rx, j):
    m = re.search(rx, j)
    return float(m.group(1)) if m else 0.0


def fixture_rows(dump):
    """-> (fingerprint, rows). A row: defName, scatter, deep, minedItem or '', isBuilding 0/1."""
    con = sqlite3.connect("file:" + dump + "?mode=ro", uri=True)
    try:
        fp = dict(con.execute("select key, value from provenance")).get("modlist_fingerprint")
        rows = []
        for name, j in con.execute("select def_name, json from defs where def_type='ThingDef'"):
            scatter = _num(r'"mineableScatterCommonality":([0-9.eE+-]+)', j)
            deep = _num(r'"deepCommonality":([0-9.eE+-]+)', j)
            mt = re.search(r'"mineableThing":"(\w+)"', j)
            building = '"building":{' in j
            if scatter > 0 or deep > 0 or mt:
                rows.append((name, scatter, deep, mt.group(1) if mt else "", 1 if building else 0))
    finally:
        con.close()
    rows.sort()
    return fp, rows


def refresh(dump):
    fp, rows = fixture_rows(dump)
    if len(rows) < 50:   # sanity: the full-list dump f1c87543 has 111 (13 scatter > 0, 21 deep > 0); Core alone has ~20
        print("REFUSED: only %d mineral defs read from %s - instrument blind?" % (len(rows), dump))
        return 1
    with open(FIXTURE, "w", encoding="utf-8", newline="\n") as f:
        f.write("# def dump modlist_fingerprint %s; columns: defName scatter deep minedItem isBuilding\n" % fp)
        for r in rows:
            f.write("%s\t%g\t%g\t%s\t%d\n" % r)
    print("WROTE %s (%d defs, dump %s)" % (FIXTURE, len(rows), fp))
    return 0


def main(argv):
    if "--refresh-fixture" in argv:
        dump = argv[argv.index("--dump") + 1] if "--dump" in argv else os.environ.get("RM_DEFDUMP_SQLITE", DUMP_DEFAULT)
        return refresh(dump)
    rc, rec = winbuild.stage_build(CSPROJ, stage_name="MineralsPolicySelfTest",
                                   extra_dirs=[os.path.join(MOD, "Source", "Kernel"), os.path.join(MOD, "Defs"), DEEP_DEFS])
    if rc:
        print("selftest build FAILED")
        return rc
    dll = winbuild.staged_win(rec, SELFTEST) + "\\bin\\Release\\net8.0\\Minerals.SelfTest.dll"
    reg = winbuild.staged_win(rec, os.path.join(MOD, "Defs")) + "\\RM_MineralRegistry.xml"
    deep = winbuild.staged_win(rec, DEEP_DEFS) + "\\RM_DeepHomeTable.xml"
    fix = winbuild.staged_win(rec, SELFTEST) + "\\mineral_defs.tsv"
    return subprocess.run([winbuild.dotnet_exe(), dll, reg, deep, fix], cwd="/mnt/d/Luke/dev").returncode


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
