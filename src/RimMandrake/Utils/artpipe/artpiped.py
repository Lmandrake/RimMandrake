class RunCtx:
    """Immutable-for-the-run configuration handed to every worker thread —
    except the codex_home leases, which are acquired LAZILY (see
    codex_home_for_slot below), one per slot, on that slot's FIRST codex
    job. A gemini-only run therefore never creates a single codex_home
    directory, never risks the one-time UAC-gated sandbox setup prompt for
    a brand-new one, and "a gemini job never touches codex homes" is true
    at the whole-daemon level, not just within process_gemini_job."""

    def __init__(self, worker_script, validator_script, manifest_schema,
                 artsrc_dir, active_dir, codex_home_root, workers_count,
                 timeout_generate, timeout_edit, reasoning_effort, verbose, slots,
                 gemini_worker_script, gemini_timeout, throughput_log=None):
        self.worker_script = worker_script
        self.validator_script = validator_script
        self.manifest_schema = manifest_schema
        self.artsrc_dir = artsrc_dir
        self.active_dir = active_dir
        self.codex_home_root = codex_home_root
        self.timeout_generate = timeout_generate
        self.timeout_edit = timeout_edit
        self.reasoning_effort = reasoning_effort
        self.verbose = verbose
        self.slots = slots  # queue.Queue of free worker-slot ints (codex channel only)
        # 🔴 Script bytes are read ONCE here and fed to every spawn via
        # stdin (`python - <args>`). Measured 2026-09-09 (mantrap_improve_b
        # r2/r3/r4/r6): drvfs intermittently served a minutes-STALE copy of
        # the worker script to some spawns — in one drain three threads ran
        # the current script and one silently ran the pre-edit version.
        # One read at ctx build makes every worker deterministically run the
        # same code; cwd stays at the script's own directory so a worker's
        # sibling imports (the mock's _codex_mock/pnglib) still resolve.
        self.gemini_worker_script = Path(gemini_worker_script)
        self.gemini_worker_source = self.gemini_worker_script.read_text()
        self.gemini_timeout = gemini_timeout
        # Needed ONLY so process_gemini_job can write a billing-INTENT row
        # (_write_gemini_billing_intent) before it spawns the worker
        # subprocess — see that function's own docstring for the crash
        # window this closes. None is tolerated (skips the intent write)
        # so any test/caller that never cared about that crash window
        # doesn't have to thread a throughput_log through just to build a
        # RunCtx.
        self.throughput_log = throughput_log
        # No `dry_run` field: --dry-run is handled entirely in main()'s
        # run_dry_run(), before a RunCtx is ever built.

        self._codex_homes: list[Path | None] = [None] * workers_count
        self.lease_handles: list = []  # closed by main() at shutdown
        self._lease_lock = threading.Lock()

    def codex_home_for_slot(self, slot: int) -> Path:
        """Acquire (once) and cache the leased codex_home for this slot.
        Guarded by a lock: two threads could in principle race to be the
        FIRST codex job on the same never-yet-used slot (unlikely — a slot
        is only handed to one thread at a time via ctx.slots — but this is
        the cheap, correct way to be sure rather than relying on that)."""
        with self._lease_lock:
            if self._codex_homes[slot] is None:
                home, fh = common.acquire_codex_home_lease(self.codex_home_root)
                self._codex_homes[slot] = home
                self.lease_handles.append(fh)
            return self._codex_homes[slot]

    def any_leased_codex_home(self) -> Path | None:
        """The first codex_home this run has actually leased, or None if
        no codex job has run yet this session. Used ONLY for the
        independent meter refresh (finding 4): the weekly/5h limits are
        ACCOUNT-level, not per-codex_home, so reading from whichever
        codex_home is already leased reflects the same account state as
        any other — there is no need to lease a NEW one just to check."""
        with self._lease_lock:
            for home in self._codex_homes:
                if home is not None:
                    return home
            return None


# Downscale-legibility direction baked into EVERY in-game (transparent-bg)
# sprite prompt, so a creature reads at play size without depending on each
# job author to remember it. Earned from the frostmite zoom pilot, 2026-09-12
# (src/RimMandrake/Utils/art_zoom_sim.py, Transient/art_zoom_review_2026-09-12/):
# a thin/absent outline plus fine surface detail turns to grey mud by normal
# play zoom (~32 on-screen px), while vanilla art survives on a thick keyline,
# a few bold shapes, and body/ground value contrast. The frostmite's 32px
# legibility went 30.8 -> 49.3 once these three were applied. Phrased as
# positive states, never "no ..." (AGENTS.md rule 2) — negated tokens still
# describe the picture to the model.
_SPRITE_ART_DIRECTION = (
    "Readability at small size (the game shrinks this sprite to a few dozen "
    "on-screen pixels): trace the whole creature in a bold, clearly darker "
    "keyline about 2-3% of the body width so its silhouette reads as one clean "
    "shape when small; carry the creature's identity in a few large distinct "
    "shapes, keeping surface detail broad, because anything finer than a few "
    "percent of the body dissolves at play size; hold the overall body "
    "value clearly lighter or darker than a mid-tone ground so it stands out "
    "against terrain; and leave a clear transparent margin of about three "
    "percent of the canvas on every side of the creature, so the whole "
    "silhouette sits free of the canvas edges."
)


def build_job_prompt(job: dict) -> str:
    """A REAL per-job scratch directory (_artsrc/<job_id>/) is what makes
    the "your working directory is per-job scratch space" claim in
    AGENTS.md true — codex_image.py sets its subprocess's cwd to the output
    file's parent, so out_png living inside _artsrc/<job_id>/ IS that
    per-job cwd, not the shared _artsrc/ root every job used to collide in."""
    canvas = job["canvas"]
    parts = [f"[artpipe job {job['id']}] {job['prompt']}",
             f"Canvas: exactly {canvas['width']}x{canvas['height']} pixels."]
    bg = job.get("background") or "transparent"
    if bg == "transparent":
        parts.append("Background: a genuinely transparent alpha channel — "
                      "no backdrop, floor, shadow or gradient.")
        # In-game sprites are the ones that get downsampled onto the map;
        # a black-backdrop reference shot does not, so it skips this.
        # Style-conditional (ART_PAINTERLY_RESTORATION_1, owner, 2026-09-14):
        # this block used to be appended unconditionally so every candidate
        # would clear the (now advisory-only, never-a-rejector) legibility
        # gate — that reason is gone. The restored wave-4/5 painterly prompt
        # family already states its own outline/readability direction
        # inline ("Heavy, clean black outline... thick enough to read
        # clearly at standard RimWorld zoom and below"), so only bolt this
        # generic direction onto a job that ISN'T already asking for the
        # painterly style, instead of duplicating and diluting it.
        if "painterly" not in job["prompt"].lower():
            parts.append(_SPRITE_ART_DIRECTION)
    else:
        parts.append(f"Background: one perfectly flat solid field of {bg}, "
                      f"used nowhere in the subject.")
    if job.get("style_notes"):
        parts.append(f"Style: {job['style_notes']}")
    if job.get("facing"):
        # A bare "Facing: north." leaves the image model to guess RimWorld's
        # top-down camera convention, and it guessed wrong often enough to
        # invert whole creatures (PYRELANDS_FACING_REGRESSION_1, owner live
        # review 2026-09-14). Spell the convention out per facing.
        facing_direction = {
            "north": ("Facing: north — the creature walks AWAY from the "
                      "viewer; we see its BACK, rear haunches and the back "
                      "of its head. No face, no eyes visible."),
            "south": ("Facing: south — the creature walks TOWARD the "
                      "viewer; we see its FACE and chest straight on."),
            # Owner ruling 2026-09-16 (gizka east review): east/west must be
            # side PROFILES, never a top-down/overhead view — "strict side
            # profile" alone still let the model raise the camera.
            "east": ("Facing: east — strict side profile with the camera at "
                     "the creature's own eye level, the creature's head "
                     "points to the RIGHT edge of the image. NOT a top-down "
                     "or overhead view: we do not look down on its back, and "
                     "only the near side of the body is visible."),
            "west": ("Facing: west — strict side profile with the camera at "
                     "the creature's own eye level, the creature's head "
                     "points to the LEFT edge of the image. NOT a top-down "
                     "or overhead view: we do not look down on its back, and "
                     "only the near side of the body is visible."),
        }
        parts.append(facing_direction.get(str(job["facing"]).lower(),
                                          f"Facing: {job['facing']}."))
    return " ".join(parts)


def run_worker(worker_script: Path, subcmd: str, prompt: str, out_png: Path,
                codex_home: Path, timeout: int, schema_path: Path,
                last_msg_path: Path, reference, model, reasoning_effort,
                verbose: bool) -> tuple[int, str, str, float, bool]:
    cmd = [sys.executable, str(worker_script), subcmd,
           "--prompt", prompt, "--out", str(out_png),
           "--codex-home", str(codex_home), "--timeout", str(timeout),
           "--force", "--reasoning-effort", reasoning_effort,
           "--output-schema", str(schema_path),
           "--output-last-message", str(last_msg_path)]
    if model:
        cmd += ["--model", model]
    if reference:
        cmd += ["--image", str(reference)]
    if verbose:
        cmd.append("--verbose")

    started = time.monotonic()
    try:
        proc = subprocess.run(cmd, capture_output=True, text=True,
                               timeout=timeout + WORKER_SUBPROCESS_GRACE_S)
        return proc.returncode, proc.stdout, proc.stderr, time.monotonic() - started, False
    except subprocess.TimeoutExpired as exc:
        out = exc.stdout.decode() if isinstance(exc.stdout, bytes) else (exc.stdout or "")
        err = exc.stderr.decode() if isinstance(exc.stderr, bytes) else (exc.stderr or "")
        return 124, out, err, time.monotonic() - started, True


_GEMINI_MODEL_RE = re.compile(r"model=([^,\s]+)")


def run_gemini_worker(worker_script: Path, prompt: str, out_png: Path, reference,
                       model: str, timeout: int, canvas=None,
                       cutout: bool = False,
                       script_source: str | None = None) -> tuple[int, str, str, float, bool]:
    """gemini_image.py's CLI is much thinner than codex_image.py's: no
    --codex-home, no --output-schema/-o, no per-job structured reply — just
    `generate --prompt --out [--ref ...] --model [--size WxH]`, a plain success
    line to stdout, or a sys.exit() message to stderr on failure.

    `--size` exists because the API ignores requested dimensions and (measured
    2026-09-09, gemini-3-pro-image) returns 1024x1024 JPEG regardless — the
    worker script owns converting/downscaling to the job's exact canvas, and
    _check_size_and_validate() still verifies the result independently."""
    if script_source is not None:
        # `python - <args>` runs the ONE source read at ctx build (see
        # RunCtx.gemini_worker_source) — immune to drvfs serving a stale
        # copy of the file to this particular spawn. cwd = the script's own
        # directory so sibling imports keep resolving.
        cmd = [sys.executable, "-", "generate"]
    else:
        cmd = [sys.executable, str(worker_script), "generate"]
    cmd += ["--prompt", prompt, "--out", str(out_png), "--model", model]
    if canvas:
        cmd += ["--size", f"{canvas['width']}x{canvas['height']}"]
    if cutout:
        cmd += ["--cutout"]
    if reference:
        cmd += ["--ref", str(reference)]
    started = time.monotonic()
    try:
        proc = subprocess.run(cmd, capture_output=True, text=True, timeout=timeout,
                               input=script_source,
                               cwd=str(Path(worker_script).parent))
        return proc.returncode, proc.stdout, proc.stderr, time.monotonic() - started, False
    except subprocess.TimeoutExpired as exc:
        out = exc.stdout.decode() if isinstance(exc.stdout, bytes) else (exc.stdout or "")
        err = exc.stderr.decode() if isinstance(exc.stderr, bytes) else (exc.stderr or "")
        return 124, out, err, time.monotonic() - started, True


def run_validator(validator_script: Path, reference, candidate: Path,
                   timeout: float = VALIDATOR_TIMEOUT_S):
    """Returns (verdict, findings). `timeout` defaults to the real
    VALIDATOR_TIMEOUT_S; overridable so a selftest can prove the
    TimeoutExpired path never raises without actually waiting 60s for it.
    verdict is one of:
      None               — skipped, no reference on this job (never a silent pass)
      "pass"              — validate_sprite.py exit 0
      "reject"            — exit 1: the IMAGE is not shippable
      "cannot_validate"   — exit 2, EXACTLY: the INPUT was unusable (e.g. a
                             missing/unreadable reference path) — a data
                             problem on the job, never the same thing as the
                             worker having produced a bad image.
      "validator_error"   — the validator itself could not be RUN or could
                             not finish at all (missing/non-executable
                             script, it timed out, or it exited with
                             anything other than its own documented 0/1/2) —
                             the validator's OWN failure, never blamed on
                             the job's reference the way exit 2 is. NEVER
                             raises past this function — a subprocess
                             timeout used to propagate as a bare
                             TimeoutExpired into the caller, which (before
                             this fix) could lose the job's channel/cost in
                             a generic exception fallback.
    """
    if not reference:
        return None, ["no reference on this job — validator skipped, not a pass"]
    # A missing validator script makes `python3 <missing>.py` exit 2 from
    # the LAUNCHER's own "can't open file" error — which coincidentally
    # collides with validate_sprite.py's own documented exit-2 meaning
    # ("bad reference input"), and would otherwise be silently
    # misattributed to the job. Checked explicitly, before ever spawning
    # anything, so this specific collision can't happen.
    if not Path(validator_script).is_file():
        return "validator_error", [f"validator script does not exist: {validator_script}"]
    try:
        proc = subprocess.run(
            [sys.executable, str(validator_script), "--reference", str(reference),
             "--candidate", str(candidate)],
            capture_output=True, text=True, timeout=timeout)
    except subprocess.TimeoutExpired:
        return "validator_error", [f"validate_sprite.py did not finish within "
                                    f"{timeout}s — the validator itself "
                                    f"is the problem here, not the job's reference"]
    except OSError as exc:
        return "validator_error", [f"could not run validate_sprite.py at "
                                    f"{validator_script}: {exc}"]
    findings = (proc.stdout + proc.stderr).strip().splitlines()
    if proc.returncode == 0:
        return "pass", findings
    if proc.returncode == 1:
        return "reject", findings
    if proc.returncode == 2:
        return "cannot_validate", findings
    # Any OTHER exit code (a crash, an uncaught exception inside the
    # validator, a nonstandard interpreter exit) is ALSO the validator's
    # own problem — not exit 2's documented "unusable input" meaning, and
    # not a REJECT either.
    return "validator_error", findings + [
        f"validate_sprite.py exited {proc.returncode} — not its documented "
        f"0 (pass) / 1 (reject) / 2 (bad input); the validator itself is the "
        f"problem here"]


