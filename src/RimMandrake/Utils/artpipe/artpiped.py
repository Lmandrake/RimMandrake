FACTS_SINGLE_FILE_CHECKS = ("transparency_real", "boundaries_respected", "outline_coherence")


def run_facts_gate(candidate: Path):
    """Returns (verdict, details). verdict is pass | reject | gate_error | skipped.

    Rejects on a `high` severity finding only. Severity is the checker's data; the
    decision to refuse is made HERE, so the checker never grows a policy.
    """
    if os.environ.get("ARTPIPE_FACTS_GATE", "0") not in ("1", "true", "yes"):
        return "skipped", []
    try:
        sys.path.insert(0, str(common.REPO_ROOT / "src" / "RimMandrake" / "Utils"))
        import art_checks
    except Exception as exc:                                  # noqa: BLE001
        return "gate_error", [f"could not import art_checks: {exc}"]
    try:
        sprite = art_checks.load(Path(candidate))
        findings = []
        for name in FACTS_SINGLE_FILE_CHECKS:
            findings.extend(getattr(art_checks, name)(sprite))
    except Exception as exc:                                  # noqa: BLE001
        return "gate_error", [f"art_checks raised on {candidate.name}: {exc}"]
    high = [f for f in findings if f.severity == "high"]
    details = [f"{f.check}: {f.detail}" for f in findings]
    return ("reject" if high else "pass"), details


def run_legibility_gate(candidate: Path, timeout: float = LEGIBILITY_TIMEOUT_S,
                         drawsize: float = 1.0):
    """Downscale-legibility gate, same error discipline as run_validator:
      None          — skipped (no thresholds file yet) — never a silent pass
      "pass"        — art_legibility.py gate exit 0
      "reject"      — exit 1: the sprite scores under the calibrated line
      "gate_error"  — the gate itself could not run/finish; infrastructure,
                       never blamed on the job
    """
    # ARTPIPE_LEGIBILITY_THRESHOLDS overrides the thresholds path. DEFAULT IS
    # DISABLED (ART_PAINTERLY_RESTORATION_1, owner, 2026-09-14 — the hard
    # gate is reversed): an unset env var now means OFF, same as an explicit
    # ''. Set it to a real thresholds-file path to opt back in. Read per
    # call, not at import, so a test (or a re-funded gate) can flip it
    # without reimporting the module.
    env_th = os.environ.get("ARTPIPE_LEGIBILITY_THRESHOLDS")
    thresholds = Path(env_th) if env_th else None
    if thresholds is None:
        return None, ["gate disabled by default (ART_PAINTERLY_RESTORATION_1) — "
                      "set ARTPIPE_LEGIBILITY_THRESHOLDS=<path> to re-enable; "
                      "skipped, not a pass"]
    if not thresholds.is_file():
        return None, [f"no thresholds file at {thresholds} — "
                      f"legibility gate skipped, not a pass"]
    if not LEGIBILITY_SCRIPT.is_file():
        return "gate_error", [f"gate script does not exist: {LEGIBILITY_SCRIPT}"]
    env_model = os.environ.get("ARTPIPE_LEGIBILITY_MODEL")
    model = LEGIBILITY_MODEL if env_model is None else (Path(env_model) if env_model else None)
    cmd = [sys.executable, str(LEGIBILITY_SCRIPT), "gate", str(candidate),
           "--thresholds", str(thresholds)]
    if model is not None and model.is_file():
        cmd += ["--model", str(model)]
        if drawsize and drawsize != 1.0:
            cmd += ["--drawsize", str(drawsize)]
    try:
        proc = subprocess.run(cmd, capture_output=True, text=True, timeout=timeout)
    except subprocess.TimeoutExpired:
        return "gate_error", [f"art_legibility.py did not finish within {timeout}s"]
    except OSError as exc:
        return "gate_error", [f"could not run art_legibility.py: {exc}"]
    findings = (proc.stdout + proc.stderr).strip().splitlines()
    if proc.returncode == 0:
        return "pass", findings
    if proc.returncode == 1:
        return "reject", findings
    if proc.returncode == 3:
        return "borderline", findings
    return "gate_error", findings + [
        f"art_legibility.py exited {proc.returncode} — not its documented 0/1/3"]


def _check_size_and_validate(result: dict, job: dict, reference, out_png: Path,
                              validator_script: Path) -> dict:
    """Common tail for BOTH channels once a real image file exists: read its
    ACTUAL dimensions — the image tool is KNOWN to ignore requested size
    (design addendum §2.3; this is the NORMAL case, not an edge case) — and
    compare against job['canvas']. A size mismatch is its own failure kind,
    checked and reported BEFORE the validator runs at all, so a
    reference-less job (which the validator skips entirely) can no longer
    accept ANY returned image as "ok" just because there was nothing to
    reject it."""
    try:
        info = codex_image.png_info(out_png)
    except (ValueError, OSError) as exc:
        result.update(status="failed", worker_status="unreadable_png", validator="not_run",
                       note=f"could not read the returned file's PNG header: {exc}")
        return result
    result["width"] = info["width"]
    result["height"] = info["height"]

    canvas = job["canvas"]
    if (info["width"], info["height"]) != (canvas["width"], canvas["height"]):
        result.update(status="failed", worker_status="size_mismatch", validator="not_run",
                       note=f"returned {info['width']}x{info['height']}, job asked for "
                            f"{canvas['width']}x{canvas['height']} — the image tool is known "
                            f"to ignore requested size; never a silent ok, reference or not")
        return result

    verdict, findings = run_validator(validator_script, reference, out_png)
    result["validator_findings"] = findings
    if verdict == "reject":
        result.update(status="failed", worker_status="worker_reported_ok_but_invalid",
                       validator="REJECT",
                       note="validate_sprite.py rejected the returned file — "
                            "the worker's own manifest is never trusted")
        return result
    if verdict == "validator_error":
        # The validator ITSELF could not be run or finish — never blamed on
        # the job's reference (that's exit-2's meaning, checked separately
        # below). This is infrastructure broken, not a bad job.
        result.update(status="failed", worker_status="validator_could_not_run",
                       validator="ERROR",
                       note=("validate_sprite.py could not be run/finish — "
                             + ("; ".join(findings[-2:]) if findings else "no detail"))[:200])
        return result
    if verdict == "cannot_validate":
        # exit 2: the INPUT was unusable (e.g. a missing/unreadable
        # reference path) — a data problem on the JOB, not the same failure
        # as the worker having produced a bad image.
        result.update(status="failed", worker_status="bad_reference_path",
                       validator="CANNOT_VALIDATE",
                       note="validate_sprite.py could not judge this at all "
                            "(exit 2, unusable input) — most likely a bad or "
                            "missing reference path on the job, not an image defect")
        return result

    # Geometry/alpha passed (or had no reference). Now the legibility gate —
    # transparent-bg sprites only: black-backdrop reference shots are never
    # downsampled onto the map, so play-zoom legibility is not their test.
    if (job.get("background") or "transparent") == "transparent":
        art_class, job_ds = _job_art_info(job.get("id") or out_png.stem, job)
        if art_class == "flora":
            # Flora has no calibrated bar yet (FLORA_LEGIBILITY_BAR_1) and the
            # vanilla convention is outline-free — never gate flora on the
            # creature model, never stroke it. Skipped is said, not silent.
            result["legibility"] = "skipped (flora — no calibrated bar; creature model does not apply)"
            result.update(status="ok", worker_status="ok",
                           validator=("PASS" if verdict == "pass" else "skipped"),
                           note=("validated" if verdict == "pass" else
                                 "no reference to validate against") + "; flora ungated")
            return result
        lverdict, lfindings = run_legibility_gate(out_png, drawsize=job_ds)
        result["legibility_findings"] = lfindings
        if lverdict == "reject":
            result.update(status="failed", worker_status="legibility_below_gate",
                           validator=("PASS" if verdict == "pass" else "skipped"),
                           legibility="REJECT",
                           note=("below the calibrated downscale-legibility line — "
                                 + ("; ".join(lfindings[-1:]) if lfindings else "no detail"))[:300])
            return result
        if lverdict == "borderline":
            # Owner-APPROVED flow (A/B sheet, 2026-09-13): borderline art gets
            # the OUTSIDE keyline stroke (opacity 1.0, 2% ring — the tool's
            # locked defaults), is rescored, and promotes on a pass. Every
            # outcome is a distinct deterministic status. The pre-stroke
            # original is kept beside the output as *_prestroke.png.
            raw_keep = out_png.with_name(out_png.stem + "_prestroke.png")
            reinforced = out_png.with_name(out_png.stem + "_reinforced.png")
            try:
                rproc = subprocess.run(
                    [sys.executable, str(LEGIBILITY_SCRIPT), "reinforce",
                     str(out_png), "--out", str(reinforced)],
                    capture_output=True, text=True, timeout=LEGIBILITY_TIMEOUT_S)
            except (subprocess.TimeoutExpired, OSError) as exc:
                result.update(status="failed", worker_status="reinforce_could_not_run",
                               legibility="ERROR", note=f"reinforce failed to run: {exc}"[:200])
                return result
            rout = (rproc.stdout + rproc.stderr).strip().splitlines()
            if rproc.returncode == 4:
                result.update(status="failed", worker_status="insufficient_margin",
                               legibility="BORDERLINE",
                               note=("borderline art cannot take the outline stroke — "
                                     + ("; ".join(rout[-1:]) if rout else ""))[:300])
                return result
            if rproc.returncode != 0:
                result.update(status="failed", worker_status="reinforce_failed",
                               legibility="ERROR",
                               note=("reinforce exited %d: " % rproc.returncode
                                     + ("; ".join(rout[-1:]) if rout else ""))[:300])
                return result
            rverdict, rfindings = run_legibility_gate(reinforced, drawsize=job_ds)
            result["legibility_findings"] = lfindings + ["--- after stroke ---"] + rfindings
            if rverdict == "pass":
                shutil.copy2(out_png, raw_keep)
                shutil.copy2(reinforced, out_png)
                result.update(status="ok", worker_status="ok",
                               validator=("PASS" if verdict == "pass" else "skipped"),
                               legibility="REINFORCED_PASS",
                               note="borderline promoted by the outside keyline stroke; "
                                    "pre-stroke original kept beside it")
                return result
            result.update(status="failed", worker_status="legibility_borderline_unrescued",
                           legibility="BORDERLINE",
                           note=("still below the works line after the stroke — regenerate; "
                                 + ("; ".join(rfindings[-1:]) if rfindings else ""))[:300])
            return result
        if lverdict == "gate_error":
            result.update(status="failed", worker_status="legibility_gate_could_not_run",
                           validator=("PASS" if verdict == "pass" else "skipped"),
                           legibility="ERROR",
                           note=("art_legibility.py could not be run/finish — "
                                 + ("; ".join(lfindings[-2:]) if lfindings else "no detail"))[:200])
            return result
        result["legibility"] = "PASS" if lverdict == "pass" else "skipped"

    # FACTS gate (owner ruling 2026-09-15): "These aren't 'quality' or 'downscaling'
    # type metrics. These are basic facts that must be true." A fact may refuse, and
    # it runs here rather than as an after-the-fact sweep because "I don't want these
    # strange versions" — a defect that reaches his eye has already cost the review.
    #
    # This is NOT the fitted legibility gate he stood down: no score, no aggregate,
    # no band. Each finding is one named fact that is false about this file.
    #
    # Single-file only. Facing-set facts (height agreement, symmetry, duplicate
    # detection) need every sibling on disk and are checked by the sweep, not here.
    fverdict, ffindings = run_facts_gate(out_png)
    result["facts_findings"] = ffindings
    if fverdict == "reject":
        result.update(status="failed", worker_status="failed_art_facts",
                       validator=("PASS" if verdict == "pass" else "skipped"),
                       facts="REJECT",
                       note=("art_checks facts violated: "
                             + "; ".join(ffindings[:2]))[:200])
        return result
    if fverdict == "gate_error":
        # The checker itself broke. Never blamed on the art, and never silently
        # passed either — a fact-check that cannot run is reported as broken.
        result["facts"] = "ERROR"
    else:
        result["facts"] = "PASS"

    result.update(status="ok", worker_status="ok",
                   validator=("PASS" if verdict == "pass" else "skipped"),
                   note="validated" if verdict == "pass" else "no reference to validate against")
    return result


def process_codex_job(job: dict, job_id: str, reference, out_png: Path, ctx: RunCtx) -> dict:
    """Runs in a worker thread. Returns a result dict; touches no shared
    detector/file-move state — the caller does that after collecting the
    future, so nothing here needs a lock."""
    is_edit = bool(reference)
    subcmd = "edit" if is_edit else "generate"
    timeout = ctx.timeout_edit if is_edit else ctx.timeout_generate
    last_msg_path = ctx.active_dir / f"{job_id}.worker_last_message.json"

    slot = ctx.slots.get()
    try:
        # Lazily leased on this slot's FIRST codex job (a bounded pool of
        # "w0".."w<N-1>" directories via a cross-process flock, never one
        # per pid — restarts don't accumulate homes, or UAC prompts for a
        # brand-new one, forever — and never shared with another daemon,
        # openai/codex #11435). A run with no codex jobs never acquires one.
        codex_home = ctx.codex_home_for_slot(slot)
        meter_before = codex_grumpiness.read_meters(codex_home)
        prompt = build_job_prompt(job)

        job_started_at = time.time()
        attempts = 0
        code = out = err = None
        timed_out = False
        elapsed_total = 0.0
        last_attempt_elapsed = 0.0
        while True:
            attempts += 1
            # A stale PNG/manifest at these exact paths, left by a PREVIOUS
            # attempt (this retry, or a requeue after a fix), must never be
            # mistaken for THIS attempt's output.
            for stale in (out_png, last_msg_path):
                try:
                    stale.unlink()
                except FileNotFoundError:
                    pass
            code, out, err, elapsed, timed_out = run_worker(
                ctx.worker_script, subcmd, prompt, out_png, codex_home, timeout,
                ctx.manifest_schema, last_msg_path, reference, job.get("model"),
                ctx.reasoning_effort, ctx.verbose)
            elapsed_total += elapsed
            last_attempt_elapsed = elapsed  # PER-ATTEMPT, not summed — see note_wall_clock's
                                             # own docstring for why a retry-summed total
                                             # would report double a normal request's real cost.
            combined = (out or "") + (err or "")
            # Read the -o last-message note BEFORE deciding whether to
            # retry — a throttle visible ONLY there (clean stdout/stderr,
            # a schema-valid "refused" manifest whose note names
            # TooManyRequests) must never be retried against an already-
            # throttled account. Retry decisions used to look only at
            # stdout+stderr, checked again (identically) below AFTER the
            # loop for the final row-1 verdict — this is that same check,
            # done early enough to matter for the retry itself.
            attempt_note = ""
            if last_msg_path.is_file():
                try:
                    attempt_report = json.loads(last_msg_path.read_text())
                    if isinstance(attempt_report, dict):
                        attempt_note = str(attempt_report.get("note") or "")
                except (OSError, ValueError):
                    pass
            combined_with_note = combined + " " + attempt_note
            failed = (code != 0) or timed_out
            rate_limited_now = failed and _looks_rate_limited(combined_with_note, prompt)
            if not failed or rate_limited_now or attempts >= MAX_CODEX_ATTEMPTS:
                break
            # Retryable: a genuine tool error or timeout, NOT a throttle
            # refusal — row 1 spec allows exactly one retry.
    finally:
        # Acquisition-to-release is ALL inside this try — a mkdir/read
        # failure, a malformed job, or any other exception in between still
        # returns the slot. An exception here used to leak the slot
        # permanently; with -N 1 that deadlocked the daemon with no SIGTERM
        # escape (queue.Queue.get() has no timeout).
        ctx.slots.put(slot)

    # `after_mtime=job_started_at` is the fix for a real bug: without a
    # floor, a worker that died before writing its own rollout would leave
    # read_meters() reading whatever this codex_home last wrote for a
    # PREVIOUS job, misattributing its meters to this one.
    meter_after = codex_grumpiness.read_meters(codex_home, after_mtime=job_started_at)

    manifest_present = last_msg_path.is_file()
    worker_self_report = None
    if manifest_present:
        try:
            worker_self_report = json.loads(last_msg_path.read_text())
        except (OSError, ValueError):
            worker_self_report = None
    # The -o last-message file's content now participates in row 1
    # detection (the spec names it as a source), not just the raw
    # stdout/stderr transcript — a worker that wrote a schema-valid
    # "refused" manifest whose note names a throttle is caught here too.
    worker_note = str(worker_self_report.get("note") or "") if isinstance(worker_self_report, dict) else ""
    text = (out or "") + (err or "") + " " + worker_note

    result = {"id": job_id, "channel": "codex", "elapsed_s": elapsed_total,
              "attempt_elapsed_s": last_attempt_elapsed, "mode": subcmd,
              "timed_out": timed_out, "meter_before": meter_before,
              "meter_after": meter_after, "daemon_attempts": attempts,
              "worker_self_report": worker_self_report,
              # Symmetric with process_gemini_job's own worker_stdout_tail/
              # worker_stderr_tail (CODEX_WORKER_SANDBOX_WRITE_1): every
              # codex-channel failure manifest used to say only "worker
              # exited 1, image_present=False" with the actual diagnostic —
              # codex_image.py's own "ERROR no image produced..." plus its
              # "--- last codex output ---" dump — thrown away right here,
              # never reaching done/failed/*.manifest.json. Only the LAST
              # attempt's out/err is kept (a retry's first-attempt text is
              # superseded, same as attempt_elapsed_s above). codex_image.py's
              # own error block runs past 2000 chars (its own tail plus the
              # ERROR line), so this tail is wider than gemini's 300.
              "worker_stdout_tail": (out or "")[-300:],
              "worker_stderr_tail": (err or "")[-2500:]}

    image_present = out_png.is_file()
    # A worker that RECOVERED from a throttle — its own internal first
    # attempt got TooManyRequests, it retried once (as AGENTS.md allows)
    # and succeeded, and says so HONESTLY in its note ("first attempt
    # returned TooManyRequests; retried once and succeeded") — has a note
    # that matches RATE_LIMIT_MARKERS despite exit 0 and a genuinely good
    # image. The check used to run unconditionally here and would file
    # that job failed AND latch the account hard-stop for everyone else,
    # punishing a success. Gated on the job having actually FAILED at the
    # worker level (nonzero exit/timeout, or exit 0 with no usable image) —
    # a real image on disk is never retroactively thrown away by a note's
    # own words about what happened getting there.
    worker_level_failed = (code != 0) or timed_out or not image_present
    if worker_level_failed and _looks_rate_limited(text, prompt):
        result.update(status="failed", worker_status="rate_limited",
                       validator="not_run", detector_row=1,
                       note="TooManyRequests / rate limited — hard stop, "
                            "drain queue (row 1)")
        return result

    if code != 0 or timed_out:
        result.update(status="failed", worker_status="worker_error",
                       validator="not_run",
                       note=(f"worker exited {code}, image_present={image_present} — "
                             f"a failed/timed-out run is never trusted regardless"
                             + (" (timed out)" if timed_out else "")
                             + (f", {attempts} attempt(s)" if attempts > 1 else "")))
        return result

    if not image_present:
        if manifest_present:
            result.update(status="failed", worker_status="worker_reported_fail",
                           validator="not_run",
                           note="exit 0, a manifest exists, but no image — "
                                "the worker reported failure/refusal honestly")
        else:
            # Row 5: exit 0 with no manifest and no image is the `--`-trap
            # no-op — fail THIS request, never the account.
            result.update(status="failed", worker_status="no_manifest",
                           validator="not_run", detector_row=5,
                           note="exit 0, no manifest, no image — the `--` "
                                "no-op (row 5): fails the request, not the account")
        return result

    return _check_size_and_validate(result, job, reference, out_png, ctx.validator_script)


def process_gemini_job(job: dict, job_id: str, reference, out_png: Path, ctx: RunCtx) -> dict:
    """Never touches ctx.slots or a codex_home — the codex grumpiness
    detector does not gate this channel at all (spec); admission is via
    GeminiBudget in the main loop instead."""
    prompt = build_job_prompt(job)
    try:
        out_png.unlink()
    except FileNotFoundError:
        pass

    model = job.get("model") or DEFAULT_GEMINI_MODEL

    # Written BEFORE the subprocess spawns, deliberately — this is the
    # ONLY record of this job that exists during the actual API call, and
    # the API call is real money in flight for however long it takes. If
    # the daemon dies right here, reconcile() finds this row via
    # _throughput_has_entry() and refuses to silently requeue the job (see
    # reconcile()'s own docstring) — a human has to look, instead of the
    # crash silently double-spending on retry. ctx.throughput_log is None
    # only for callers (tests) that never wired one up; skip rather than
    # crash on write.
    if ctx.throughput_log is not None:
        _write_gemini_billing_intent(ctx.throughput_log, job_id)

    code, out, err, elapsed, timed_out = run_gemini_worker(
        ctx.gemini_worker_script, prompt, out_png, reference, model, ctx.gemini_timeout,
        canvas=job.get("canvas"),
        cutout=(job.get("background", "transparent") == "transparent"),
        script_source=getattr(ctx, "gemini_worker_source", None))

    m = _GEMINI_MODEL_RE.search(out or "")
    actual_model = m.group(1) if m else model

    # cost_usd starts at 0.0 and is set ONLY once a real image is confirmed
    # on disk (below) — computing it from `code == 0` alone used to bill an
    # exit-0-but-no-image no-op, which is not a genuine success. "Only a
    # genuinely successful call is billable" means an image actually landed,
    # not merely that the process exited 0.
    result = {"id": job_id, "channel": "gemini", "elapsed_s": elapsed,
              "timed_out": timed_out, "model": actual_model, "cost_usd": 0.0,
              "meter_before": None, "meter_after": None, "daemon_attempts": 1,
              # The worker's own success line states what it believes it wrote
              # ("... 1024x1024 -> 256x256 png"); kept on every manifest so a
              # worker-says vs daemon-reads mismatch is diagnosable from the
              # manifest alone (it cost three blind retries on 2026-09-09).
              "worker_stdout_tail": (out or "")[-300:],
              "worker_stderr_tail": (err or "")[-300:]}

    if code != 0 or timed_out:
        # A quota/429 exhaustion is NOT an ordinary worker fault: hammering
        # it again next tick just burns wall-clock against a provider that
        # has already said no. finalize_job's gemini branch reads this
        # worker_status back to drive GeminiBudget's backoff (see
        # note_quota_error/note_recovered) — every OTHER failure counts as
        # "recovered" (resets any existing backoff streak), since a normal
        # error says nothing about the provider's own rate-limit state.
        is_quota = _looks_gemini_quota_error(err) or _looks_gemini_quota_error(out)
        result.update(status="failed",
                       worker_status="quota_error" if is_quota else "worker_error",
                       validator="not_run",
                       note=(f"gemini worker exited {code}"
                             + (" (timed out)" if timed_out else "")
                             + (f": {err.strip()[-200:]}" if err else "")))
        return result

    if not out_png.is_file():
        result.update(status="failed", worker_status="no_manifest", validator="not_run",
                       note="exit 0 but no image was written")
        return result

    # Now, and only now, with a real file confirmed to exist: this is
    # billable regardless of what the size check / validator decide next —
    # the API call itself succeeded and returned pixels.
    result["cost_usd"], unrecognised_model_note = _gemini_model_cost(actual_model)
    if unrecognised_model_note:
        # Internal-only key: finalize_job (main thread) pops this and hands
        # it to console.note() — never written into the manifest itself.
        result["_console_note"] = unrecognised_model_note

    return _check_size_and_validate(result, job, reference, out_png, ctx.validator_script)


def process_job(job_path: Path, ctx: RunCtx) -> dict:
    """The one hard rule here: whatever comes back ALWAYS carries the
    correct `channel` and a `cost_usd` the caller can trust — even on a
    totally unexpected exception. Before this, an exception raised inside
    process_gemini_job (run_validator's own subprocess.run could raise
    TimeoutExpired straight through it) propagated all the way to main()'s
    generic `except Exception` fallback, which built a result with NO
    `channel` key at all — finalize_job then defaulted it to "codex" and
    silently billed a REAL gemini spend as $0 against the wrong channel,
    permanently under-counting the durable budget read back from
    throughput.jsonl. run_validator no longer raises (it returns a
    "validator_error" verdict instead), so this is now a pure safety net,
    but the net is real: it is the only thing that can still see the
    correct channel if some other, truly unanticipated exception occurs.
    """
    try:
        job = common.load_job(job_path)
    except common.JobError as exc:
        # _channel_of() reads the raw JSON directly rather than trusting
        # common.load_job's strict parse (which just failed) — a malformed
        # GEMINI job used to fall back to a hardcoded "codex" here, so
        # finalize_job's gemini branch (which releases the claim-time
        # reservation) never ran for it: the reservation leaked forever,
        # and enough malformed gemini jobs would eventually block the
        # WHOLE gemini channel at $0 real spend (reserved_usd alone
        # reaching the cap). _channel_of() degrades to "codex" only when
        # the file is truly unreadable, which is the same failure mode
        # either way.
        return {"id": job_path.stem, "channel": _channel_of(job_path), "status": "failed",
                "note": str(exc), "worker_status": "bad_job_file", "validator": "not_run",
                "cost_usd": 0.0}

    job_id = job["id"]
    channel = job.get("channel") or "codex"
    reference = job.get("reference")
    job_scratch = ctx.artsrc_dir / job_id  # a REAL per-job scratch dir — see build_job_prompt()
    out_png = job_scratch / f"{job_id}.png"

    if channel == "gemini":
        try:
            return process_gemini_job(job, job_id, reference, out_png, ctx)
        except Exception as exc:
            return {"id": job_id, "channel": "gemini", "status": "failed", "cost_usd": 0.0,
                    "worker_status": "daemon_error", "validator": "not_run",
                    "note": (f"process_gemini_job raised {type(exc).__name__}: {exc} — "
                             f"billed $0.0 because no confirmed cost survives this exception; "
                             f"if the API call had already succeeded, check the worker's own "
                             f"logs/billing directly")[:400]}
    if channel != "codex":
        return {"id": job_id, "channel": channel, "status": "failed", "cost_usd": 0.0,
                "worker_status": "bad_job_file", "validator": "not_run",
                "note": f"unknown channel {channel!r} — only 'codex' or 'gemini'"}
    try:
        return process_codex_job(job, job_id, reference, out_png, ctx)
    except Exception as exc:
        return {"id": job_id, "channel": "codex", "status": "failed",
                "worker_status": "daemon_error", "validator": "not_run",
                "note": f"process_codex_job raised {type(exc).__name__}: {exc}"}


def finalize_job(job_path: Path, result: dict, done_dir: Path, failed_dir: Path,
                  active_dir: Path, throughput_log: Path, detector: Detector,
                  gemini_budget: GeminiBudget, configured_n: int,
                  reserved_usd: float = 0.0,
                  console_obj: "console.Console | None" = None) -> None:
    """`reserved_usd` MUST be the exact amount THIS job's own claim-time
    reserve() call actually reserved — 0.0 for anything that never
    reserved at all (a non-gemini job, or a gemini job from the
    JobError/exception fallbacks that never got a chance to claim/reserve
    in the first place). Releasing a fixed constant regardless used to
    let a job that never reserved anything "release" (steal) budget out
    of a DIFFERENT job's real, outstanding reservation.

    `console_obj`, if given, is ARTPIPE_CONSOLE_REDESIGN_1's presentation
    hook — optional (default None) so any other/future caller that builds
    no Console at all still works unchanged."""
    job_id = result.get("id", job_path.stem)
    channel = result.get("channel", "codex")
    ok = result.get("status") == "ok"
    target_dir = done_dir if ok else failed_dir

    # A note stashed by a WORKER THREAD (process_gemini_job's
    # _gemini_model_cost call) that could not reach the console itself —
    # worker threads never touch it (see console.py's module docstring).
    # Popped here, on the main thread, before anything below writes
    # `result` to the manifest, so the manifest never carries this
    # internal-only key.
    deferred_note = result.pop("_console_note", None)
    if deferred_note and console_obj is not None:
        console_obj.warn(deferred_note)

    # Throughput FIRST, before the manifest write or the job-file move: a
    # crash in between those two steps used to lose the cost row entirely
    # (the manifest — moved or not — still carries cost_usd, but
    # read_gemini_spend() only ever sums throughput.jsonl, never scans
    # manifests). One cheap atomic append, moved earlier, closes THAT
    # window.
    #
    # ⚠️ CORRECTED CLAIM (an earlier version of this comment was wrong):
    # a crash in the NEW gap this creates — after this append succeeds but
    # BEFORE the manifest write below — is NOT free of double-counting
    # risk. On the next start, reconcile() sees active/<id>.json with no
    # manifest anywhere and treats it as an ordinary orphan, requeuing it
    # to pending/ for a full fresh retry — but a throughput row for this
    # id ALREADY exists from the crashed attempt. For a GEMINI job that
    # already spent real money before crashing, the retry can spend it
    # AGAIN, and both rows are real — read_gemini_spend() summing both is
    # not wrong per se, but reconcile()'s silent requeue never lets a
    # human decide whether re-running is safe. Closed at the SOURCE
    # instead, in reconcile(): a gemini-channel orphan whose id already
    # has a throughput.jsonl row is routed to failed/ with an
    # "ambiguous_billing_crash" manifest and never auto-requeued — see
    # reconcile()'s own docstring.
    common.append_jsonl(throughput_log, {
        "ts": time.time(), "id": job_id, "channel": channel,
        "status": result.get("status"),
        "worker_status": result.get("worker_status"),
        "elapsed_s": result.get("elapsed_s"),
        "validator": result.get("validator"),
        "meter_before": result.get("meter_before"),
        "meter_after": result.get("meter_after"),
        "cost_usd": result.get("cost_usd"),
        "model": result.get("model"),
        "daemon_attempts": result.get("daemon_attempts"),
    })

    # ART_REGEN_REGISTRY_1: emit generated+validated through artreg — best
    # effort, never fatal to the job itself. A job filed before this wiring
    # existed (or filed by hand, with no `queued` event on record) has
    # nothing for artreg to resolve its target from; that is logged and
    # skipped rather than crashing finalize_job, which still owns getting
    # the actual image into done/failed/ regardless of registry bookkeeping.
    #
    # Only against the REAL queue (default dirs) — see the matching guard in
    # fill_queue.py's write_job for why: selftest_artpipe.py always finalizes
    # into a tempfile.TemporaryDirectory(), and without this check every
    # test run would permanently pollute the production registry.jsonl.
    if done_dir == common.DEFAULT_DONE and failed_dir == common.DEFAULT_FAILED:
        try:
            artreg.record_generated(job_id, elapsed_s=result.get("elapsed_s"), by="artpiped")
            artreg.record_validated(job_id, "pass" if ok else "fail", by="artpiped")
        except artreg.RegError as exc:
            # §8.1: log-only — the daemon's operator cannot act on this
            # (no --target to pass), so it never reaches the live console.
            note_text = (f"registry skipped for {job_id}: no queued event on record — job "
                         f"filed before the ART_REGEN_REGISTRY_1 wiring or by hand, so "
                         f"artreg cannot resolve its target (artreg: {exc})")
            if console_obj is not None:
                console_obj.note_registry_skipped(note_text)
        except Exception as exc:  # never let registry bookkeeping take the daemon down
            warn_text = (f"artreg event emit raised {type(exc).__name__} for {job_id}: {exc}")
            if console_obj is not None:
                console_obj.warn(warn_text)

    dest_job = target_dir / f"{job_id}.json"
    manifest_path = target_dir / f"{job_id}.manifest.json"
    common.atomic_write_json(manifest_path, result)
    try:
        os.replace(job_path, dest_job)
    except FileNotFoundError:
        # job_path vanished from under us — never let one job's bookkeeping
        # surprise crash the whole daemon and abandon everything else it
        # was running. `--repair` completes this exact state afterward.
        if console_obj is not None:
            console_obj.warn(f"{job_id}'s active/ file disappeared before it could be "
                             f"filed to {target_dir.name}/ — manifest written, job file "
                             f"itself is now unaccounted for (run --repair)")

    stray = active_dir / f"{job_id}.worker_last_message.json"
    if stray.is_file():
        try:
            stray.unlink()
        except OSError:
            pass

    # ARTPIPE_CONSOLE_REDESIGN_1: the permanent per-job record line, once,
    # regardless of which channel branch below runs next — everything above
    # this point (throughput, manifest, job-file move) is common to both.
    if console_obj is not None:
        console_obj.job_finished(result)

    if channel == "gemini":
        # Drops EXACTLY what this job's own claim-time reserve() call
        # reserved (0.0 if it never successfully reserved at all) and
        # records whatever it actually cost (0.0 if it never got billed)
        # — see GeminiBudget's own docstring for why the reservation
        # existed and why the amount must be tracked per-job.
        gemini_budget.release_reservation(reserved_usd, result.get("cost_usd") or 0.0)
        if result.get("worker_status") == "quota_error":
            gemini_budget.note_quota_error()
        else:
            gemini_budget.note_recovered()
        return  # the codex Detector never sees a gemini job's numbers at all

    if result.get("detector_row") == 1:
        detector.note_rate_limited()
        if console_obj is not None:
            console_obj.quota(quota_state(detector, configured_n))
    detector.note_meters(result.get("meter_after"),
                          warn=console_obj.warn if console_obj is not None else None)
    if console_obj is not None:
        console_obj.quota(quota_state(detector, configured_n))
    # PER-ATTEMPT elapsed (never the retry-summed total — a job that used
    # its one retry would otherwise report double a normal request's real
    # cost) and per-MODE (generate vs edit have different measured
    # baselines — see note_wall_clock's own docstring). Falls back to
    # elapsed_s/"generate" for any result missing the newer fields (the
    # bad_job_file/daemon_error fallbacks never reach this branch at all
    # since they're channel=="codex" but carry no elapsed_s).
    attempt_elapsed = result.get("attempt_elapsed_s", result.get("elapsed_s"))
    if attempt_elapsed is not None:
        detector.note_wall_clock(attempt_elapsed, configured_n, mode=result.get("mode", "generate"))
        if console_obj is not None:
            console_obj.quota(quota_state(detector, configured_n, slowdown=True))


