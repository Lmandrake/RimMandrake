def _gemini_model_cost(model: str) -> float:
    return GEMINI_MODEL_COST_USD.get(model, GEMINI_MODEL_COST_USD[DEFAULT_GEMINI_MODEL])


def read_gemini_spend(throughput_log: Path) -> float:
    """Sum of every past gemini job's recorded `cost_usd` in
    throughput.jsonl — the budget is DURABLE across restarts, not an
    in-memory counter that forgets everything the moment the daemon
    restarts."""
    if not throughput_log.is_file():
        return 0.0
    try:
        text = throughput_log.read_text(errors="replace")
    except OSError:
        return 0.0
    total = 0.0
    for line in text.splitlines():
        line = line.strip()
        if not line:
            continue
        try:
            obj = json.loads(line)
        except ValueError:
            continue
        if obj.get("channel") == "gemini":
            cost = obj.get("cost_usd")
            if isinstance(cost, (int, float)) and not isinstance(cost, bool):
                total += cost
    return total


class GeminiBudget:
    """Independent of the codex Detector on purpose (spec: the codex
    grumpiness detector does not gate gemini jobs). Latched, not
    de-escalating — a dollar cap does not reset itself the way a percentage
    meter resets on a rolling time window; once a run's spend reaches the
    cap it stays hit for the rest of that run.

    `reserved_usd` closes a real race: admission used to be checked ONLY at
    claim time, against `spent_usd` alone — so with N workers, up to N
    gemini jobs could all be claimed in the same instant (none of them has
    reported its cost back yet, so `spent_usd` hasn't moved), collectively
    overshooting the cap by up to (N-1) jobs' worth before any of them
    finishes. `reserve()` charges the CONSERVATIVE upper-bound estimate the
    instant a job is claimed — before it runs — so a second claim in the
    same window sees the reservation and is refused; `release_reservation()`
    drops the estimate and records the REAL cost once the job finishes,
    whatever it actually was. Reservations are never persisted — only
    realized `spent_usd` survives a restart, read from throughput.jsonl.
    """

    def __init__(self, cap_usd: float, spent_so_far: float = 0.0):
        self.cap_usd = cap_usd
        self.spent_usd = spent_so_far
        self.reserved_usd = 0.0
        self.hard_stop = spent_so_far >= cap_usd

    def reserve(self, estimated_cost_usd: float) -> bool:
        """Reserve budget for a job claimed but not yet run. Returns False
        (nothing reserved) if the cap is already spent+reserved — the
        caller must not claim in that case."""
        if self.admission_blocked() or \
           (self.spent_usd + self.reserved_usd + estimated_cost_usd) > self.cap_usd:
            return False
        self.reserved_usd += estimated_cost_usd
        return True

    def release_reservation(self, estimated_cost_usd: float, actual_cost_usd: float) -> None:
        """The job finished (success or failure) — drop its reservation and
        record whatever it actually cost (0.0 for a failure that was never
        billed)."""
        self.reserved_usd = max(0.0, self.reserved_usd - estimated_cost_usd)
        if actual_cost_usd:
            self.spent_usd += actual_cost_usd
        if self.spent_usd >= self.cap_usd:
            self.hard_stop = True

    def admission_blocked(self) -> bool:
        return self.hard_stop or (self.spent_usd + self.reserved_usd) >= self.cap_usd


# Specific throttle phrasing, not a bare "rate limited" substring — that
# loose a match collides with ordinary art-prompt vocabulary (a "rusted
# rate-limited valve" reskin prompt would trip it). "toomanyrequests" is
# camelCase and effectively never appears in natural English by accident.
RATE_LIMIT_MARKERS = ("toomanyrequests", "rate limit exceeded",
                      "was rate limited", "request was rate limited")


def _looks_rate_limited(text: str, prompt: str | None = None) -> bool:
    """Detect an explicit throttle refusal in the worker's captured stdout+
    stderr (and, at the call site, the worker's own -o last-message note —
    the spec names "-o last message" as a detection source, not just the
    raw transcript). Not a fully structured signal — codex_image.py has no
    field for "the account got throttled" distinct from its own raw output
    blob (do_image() dumps up to 2000 chars of it to stderr on ANY failure,
    --verbose or not) — so this is a best-effort text match, not the clean
    field lookup the ideal fix would use. Two mitigations against a false
    hard-stop: this job's own `prompt` — which that same dump routinely
    echoes back verbatim — is stripped out of the haystack first, and the
    remaining markers are specific throttle phrasing (see RATE_LIMIT_MARKERS)
    rather than anything a benign prompt could contain.
    """
    hay = text or ""
    if prompt:
        hay = hay.replace(prompt, "")
    hay = hay.lower()
    return any(marker in hay for marker in RATE_LIMIT_MARKERS)


