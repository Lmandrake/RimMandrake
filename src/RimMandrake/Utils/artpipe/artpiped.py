#!/usr/bin/env python3
"""artpiped.py — the art-pipeline daemon (ART_PIPELINE_DAEMON_1).

A dumb local orchestrator, no LLM of its own: scans
`infrastructure/artpipe/pending/` for job JSON files, atomic-claims them by
`os.rename` into `active/`, and runs up to N concurrent one-shot workers.
Two channels, routed per job by its `"channel"` field:

  - **codex** (default) — a `codex_image.py generate|edit` subprocess per
    job, pointed at a small POOL of leased `--codex-home` directories
    (openai/codex #11435: parallel `exec` under one shared CODEX_HOME
    interferes via shared session restore, so isolation is mandatory).
    Gated by the six-row grumpiness `Detector` below.
  - **gemini** — a `gemini_image.py generate --ref` subprocess per job. NOT
    gated by the codex Detector at all — gated instead by `GeminiBudget`, a
    dollar cap read from `throughput.jsonl` (durable across restarts) and
    hard-stopped once spend reaches `--gemini-budget-usd`.

Every returned file is re-validated independently — real dimensions read
and checked against the job's own `canvas` (the image tool is KNOWN to
ignore requested size; this is the normal case, not an edge case), then
`validate_sprite.py` if a reference exists. A worker's own self-report is
NEVER trusted for the pass/fail verdict, on either channel.

    python3 artpiped.py                       # run until SIGTERM/SIGINT
    python3 artpiped.py --once                # drain what's pending, then exit
    python3 artpiped.py --dry-run              # report what's pending, touch nothing
    python3 artpiped.py --reconcile-only       # crash recovery (+ --repair), then exit
    python3 artpiped.py --repair               # just the crash-state completion, then exit
    python3 artpiped.py --worker-script .../mock_codex_worker.py --once   # tests

Crash safety: on start, any job left in `active/` with no manifest in
`done/` or `failed/` is rename-reconciled straight back to `pending/` — a
killed daemon loses no job. A DIFFERENT crash state — the manifest got
written but the daemon died before moving the job file out of `active/` —
is deliberately left alone by `reconcile()` (guessing which of two possible
manifests is authoritative would be worse than asking); `repair()` completes
that specific, unambiguous case.

No image is ever generated by this file directly; it only ever shells out to
`--worker-script`/`--gemini-worker-script` (real tools, or mocks for testing).
"""
