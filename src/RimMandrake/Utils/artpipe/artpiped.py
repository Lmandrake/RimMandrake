def _coerce_epoch(value) -> float | None:
    """`primary_resets_at` must be a numeric unix epoch. Anything else (an
    ISO string, a seconds-remaining delta, None) is coerced to "unknown"
    rather than trusted: an ISO string would TypeError the main thread
    comparing `time.time() < sleep_until`, and a seconds-remaining value
    would compare as a tiny past epoch and silently never sleep at all —
    both worse than falling back to a value we know is safe."""
    if isinstance(value, bool):
        return None
    if isinstance(value, (int, float)):
        return float(value)
    return None


class Detector:
    """All shared admission-control state for the CODEX channel only — the
    gemini channel is gated by GeminiBudget instead (spec: "the codex
    grumpiness detector does NOT gate gemini jobs"). Touched ONLY from the
    main thread, after a job's future has completed — never from a worker
    thread — so it needs no lock of its own.

    De-escalating by design, except row 1: every threshold here is
    RECOMPUTED from the CURRENT reading on each note_meters() call, so a
    weekly usage that climbed to 93% and then reset to 1% (a new week, or a
    stale one-off bad reading) clears refuse_new/n_override/sleep_until on
    the very next healthy reading. Only `hard_stop` (row 1, an explicit
    TooManyRequests) stays latched for the rest of this run — a real
    throttle refusal is not something a later healthy meter reading should
    be allowed to paper over.
    """

    def __init__(self):
        self.hard_stop = False       # row 1: TooManyRequests — LATCHED, never clears
        self.refuse_new = False      # row 2 @ weekly >= 90 — recomputed each reading
        self.stop_all = False        # row 2 @ weekly >= 97 — recomputed each reading
        self.warn_logged = False     # row 2 @ weekly >= 80 — clears below 80 so it can re-fire
        # ARTPIPE_QUOTA_RESET_WEDGE_1: the account's own reported weekly
        # reset time (codex_grumpiness.classify()'s secondary_resets_at —
        # already read off the SAME rollout as primary_resets_at, just
        # never stored before this). Once refuse_new/stop_all is set, the
        # only path back to admitting a codex job used to be a FRESH
        # rollout on disk — but a fresh rollout is only ever written by a
        # codex job actually running, and admission_blocked() refuses every
        # new codex job while refuse_new/stop_all is set, so the daemon
        # could not write its own way out; it stayed parked until an
        # OUTSIDE process (a human's manual `codex exec` in the same leased
        # codex_home) happened to refresh the rollout, or until a restart.
        # Remembering this timestamp gives admission_blocked() the same
        # self-heal row 3 already has via sleep_until — no extra API call,
        # no guessed poll interval, just trusting the deadline Codex itself
        # already reported.
        self.weekly_resets_at = None
        self.n_override = None       # row 3 @ 5h >= 70 -> N=1 — recomputed each reading
        self.sleep_until = None      # row 3 @ 5h >= 90 -> sleep to resets_at — recomputed
        self.wall_clock_history: dict[str, list[float]] = {}  # keyed by mode ("generate"/"edit")
        self._slow_streak: dict[str, int] = {}
        self.effective_n = None      # row 4: halved on a sustained slowdown (one-way ratchet)
        # ARTPIPE_CONSOLE_REDESIGN_1: read-only bookkeeping, no decision logic
        # of its own — these exist purely so quota_state() (below) can build
        # a console.QuotaState snapshot without the console ever reaching
        # into Detector internals directly. Nothing here changes what any
        # threshold decides.
        self.last_weekly_pct: float | None = None       # last note_meters() weekly reading
        self.last_five_h_pct: float | None = None        # last note_meters() 5h reading
        self.last_slowdown_mode: str | None = None        # mode that most recently tripped row 4
        self.last_slowdown_median_s: float | None = None  # its rolling median at that moment
        self.last_slowdown_baseline_s: float | None = None  # that mode's baseline

    def note_rate_limited(self) -> None:
        self.hard_stop = True

    def note_meters(self, meters: dict | None, warn=None) -> None:
        """`meters` is codex_grumpiness.read_meters()'s own return shape —
        `{"ok": bool, "secondary_used_percent":.., "primary_used_percent":..,
        "primary_resets_at":..}` — not a raw rate_limits object. `ok: False`
        (no rollout yet, or none new enough) is ignorance: state is left
        UNCHANGED, neither reset to healthy nor held at whatever it was.

        `warn`, if given, is a `Callable[[str], None]` (in practice
        `console.Console.warn`) the caller wires in so this method's own
        infrastructure warning (an unusable `primary_resets_at`) reaches the
        console/log surface without Detector importing or knowing about
        Console at all — ARTPIPE_CONSOLE_REDESIGN_1, §8 line 352."""
        if not meters or not meters.get("ok"):
            return
        weekly = meters.get("secondary_used_percent")
        five_h = meters.get("primary_used_percent")
        resets_raw = meters.get("primary_resets_at")
        weekly_resets_raw = meters.get("secondary_resets_at")

        if weekly is not None:
            self.last_weekly_pct = weekly
            self.stop_all = weekly >= WEEKLY_STOP
            self.refuse_new = (not self.stop_all) and weekly >= WEEKLY_REFUSE
            # ARTPIPE_QUOTA_RESET_WEDGE_1: remember the best-known weekly
            # reset deadline on every reading we get, regardless of band —
            # a coercible value here is the ONLY thing that lets
            # admission_blocked() ever recover once refuse_new/stop_all
            # latches (see that method and the field's own docstring above).
            coerced_weekly_reset = _coerce_epoch(weekly_resets_raw)
            if coerced_weekly_reset is not None:
                self.weekly_resets_at = coerced_weekly_reset
            if weekly >= WEEKLY_WARN:
                # ARTPIPE_CONSOLE_REDESIGN_1, §8 line 339: the once-only
                # WARNING print here is REPLACED by Console.quota()'s own
                # refuse/stop transition lines — warn_logged itself stays
                # (still de-escalates below 80 so it can refire), it just no
                # longer prints anything on its own.
                self.warn_logged = True
            else:
                self.warn_logged = False  # de-escalate: a fresh low reading can warn again later

        if five_h is not None:
            self.last_five_h_pct = five_h
            if five_h >= FIVE_H_SLEEP:
                coerced = _coerce_epoch(resets_raw)
                if coerced is not None:
                    self.sleep_until = coerced
                    self.n_override = None
                else:
                    if warn is not None:
                        warn(f"primary_resets_at is not a usable epoch "
                             f"({resets_raw!r}) — five-hour usage is >= {FIVE_H_SLEEP:.0f}% "
                             f"but falling back to N=1 instead of a sleep gate I cannot trust")
                    self.sleep_until = None
                    self.n_override = 1
            elif five_h >= FIVE_H_DROP_N1:
                self.n_override = 1
                self.sleep_until = None
            else:
                self.n_override = None
                self.sleep_until = None

    def note_wall_clock(self, seconds: float, configured_n: int, mode: str = "generate") -> None:
        """Row 4 spec, literally: the ROLLING MEDIAN of the last 5 wall-clock
        readings, checked against 2x baseline, for 3 CONSECUTIVE calls —
        not "the last 3 readings were each individually slow". A single
        outlier (one very slow request among four fast ones) moves the
        median far less than it would move a naive "all of the last 3"
        check, which is the point of using a median here at all.

        `mode` ("generate" or "edit") keeps a SEPARATE history/baseline/
        streak per mode — generate's month-long measured median (62s) and
        edit's (150s, from a much rougher measurement) are not the same
        population, and pooling them made an edit-heavy workload trip this
        row constantly under perfectly ordinary conditions. `seconds`
        should be ONE ATTEMPT's own wall clock, never a retry-summed total
        — a job that needed its one allowed retry would otherwise report
        double its real per-request time, again lookng artificially slow
        for no operational reason. `effective_n` (the actual concurrency
        cut) stays a single daemon-wide value — only the SLOWDOWN DETECTION
        is per-mode.

        Timeouts DO reach this method, correctly: a timed-out request is
        definitionally the slowest possible one, and this row's job is to
        notice a sustained slowdown, timeouts included. What must NEVER
        reach note_rate_limited (row 1) is a plain timeout — only an
        explicit TooManyRequests/rate-limited text match does that (see
        _looks_rate_limited and its call site) — so a slow-but-real request
        cannot masquerade as a throttle refusal, even though it is exactly
        the kind of thing that SHOULD slow this row down.
        """
        baseline = _baseline_for_mode(mode)
        history = self.wall_clock_history.setdefault(mode, [])
        history.append(seconds)
        del history[:-5]
        median = statistics.median(history)
        streak = self._slow_streak.get(mode, 0)
        if median > baseline * WALL_CLOCK_MULTIPLIER:
            streak += 1
        else:
            streak = 0
        self._slow_streak[mode] = streak
        if streak >= WALL_CLOCK_STREAK:
            base = self.effective_n if self.effective_n is not None else configured_n
            self.effective_n = max(1, base // 2)
            self._slow_streak[mode] = 0  # don't re-trigger every single tick thereafter
            # ARTPIPE_CONSOLE_REDESIGN_1: read-only bookkeeping only — lets
            # quota_state() render the "sustained slowdown (edit median
            # 340s vs 150s baseline)" console line without this method
            # gaining any console/logic dependency.
            self.last_slowdown_mode = mode
            self.last_slowdown_median_s = median
            self.last_slowdown_baseline_s = baseline

    def _weekly_window_should_have_reset(self) -> bool:
        """ARTPIPE_QUOTA_RESET_WEDGE_1: True once wall-clock time has passed
        the last weekly reset deadline Codex itself reported. stop_all/
        refuse_new stay stale-True until a real note_meters() call recomputes
        them (see that method's docstring — only row 1 is meant to stay
        latched) — this just stops admission_blocked() from treating that
        stale True as gospel past its own known expiry, the same way
        sleep_until already stops blocking row 3 once time.time() passes it.
        A job admitted on this basis gets a REAL fresh reading via the
        ordinary finalize_job -> note_meters() path, which confirms or
        re-blocks; no extra API call is spent finding this out."""
        return self.weekly_resets_at is not None and time.time() >= self.weekly_resets_at

    def admission_blocked(self) -> bool:
        if self.hard_stop:
            return True
        if (self.stop_all or self.refuse_new) and not self._weekly_window_should_have_reset():
            return True
        if self.sleep_until and time.time() < self.sleep_until:
            return True
        return False

    def current_n(self, configured_n: int) -> int:
        n = configured_n
        if self.n_override is not None:
            n = min(n, self.n_override)
        if self.effective_n is not None:
            n = min(n, self.effective_n)
        return max(1, n)


def quota_state(detector: Detector, configured_n: int, *, slowdown: bool = False) -> console.QuotaState:
    """Build the console's own `QuotaState` snapshot from `Detector`'s
    public fields — the ONLY place artpiped.py hands codex quota facts to
    the console. `slowdown=True` is passed only at the call site right
    after `detector.note_wall_clock()` (see `console.QuotaState`'s own
    docstring for why that call site, specifically, is what makes the
    row-4/row-3 concurrency-drop distinction unambiguous for
    `console._quota_diff_lines`)."""
    return console.QuotaState(
        weekly_pct=detector.last_weekly_pct,
        five_h_pct=detector.last_five_h_pct,
        weekly_resets_at=detector.weekly_resets_at,
        sleep_until=detector.sleep_until,
        refuse_new=detector.refuse_new,
        stop_all=detector.stop_all,
        hard_stop=detector.hard_stop,
        admission_blocked=detector.admission_blocked(),
        current_n=detector.current_n(configured_n),
        slowdown_mode=detector.last_slowdown_mode if slowdown else None,
        slowdown_median_s=detector.last_slowdown_median_s if slowdown else None,
        slowdown_baseline_s=detector.last_slowdown_baseline_s if slowdown else None,
    )


