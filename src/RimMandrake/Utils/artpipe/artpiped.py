def default_reconcile_min_age(timeout_edit: int, gemini_timeout: int = DEFAULT_GEMINI_TIMEOUT_S) -> float:
    """The real worst case ANY single job — codex or gemini — can
    legitimately still be running, times a GENEROUS safety margin, not a
    razor-thin one.

    codex: one attempt's outer ceiling (--timeout-edit +
    WORKER_SUBPROCESS_GRACE_S), times the max attempts a row-1 retry can
    cost, plus the validator's own timeout.
    gemini: --gemini-timeout (no retry — process_gemini_job has none)
    plus the validator's own timeout.

    This used to derive from --timeout-edit ALONE — a hardcoded 600s
    default had only 40s of margin over codex's worst case at ITS
    default, and didn't move if --timeout-edit was raised; separately,
    ignoring --gemini-timeout entirely meant raising IT past roughly 530s
    let a still-genuinely-running gemini job get stolen back by
    reconcile() as a false orphan. Taking the max of both configured
    values is what makes raising EITHER timeout safe.
    """
    codex_worst_case = (timeout_edit + WORKER_SUBPROCESS_GRACE_S) * MAX_CODEX_ATTEMPTS \
        + VALIDATOR_TIMEOUT_S
    gemini_worst_case = gemini_timeout + VALIDATOR_TIMEOUT_S
    return max(codex_worst_case, gemini_worst_case) * 1.5


def run_dry_run(args: argparse.Namespace) -> int:
    """Report what WOULD run, touching nothing — not even reconcile(), which
    can move a file, and --dry-run promises it never does."""
    try:
        candidates = sorted(args.pending_dir.glob("*.json"),
                            key=lambda p: (_priority_of(p), p.name))
    except OSError:
        candidates = []

    if not candidates:
        print("artpiped: --dry-run, nothing pending")
        return 0

    for p in candidates:
        try:
            job = common.load_job(p)
        except common.JobError as exc:
            print(f"would FAIL to claim {p.name}: {exc}")
            continue
        channel = job.get("channel") or "codex"
        is_edit = bool(job.get("reference"))
        subcmd = "edit" if is_edit else "generate"
        out_png = args.artsrc_dir / job["id"] / f"{job['id']}.png"
        print(f"would claim {p.name} [{channel}]: {subcmd} -> {out_png}")
        if args.verbose:
            print(f"    prompt: {build_job_prompt(job)}")

    print(f"\nartpiped: --dry-run, {len(candidates)} job(s) would be claimed — "
          f"pending/ left untouched, no worker spawned")
    return 0


def _status_pid_alive(pid) -> bool:
    if not isinstance(pid, int):
        return False
    try:
        os.kill(pid, 0)
    except ProcessLookupError:
        return False
    except PermissionError:
        return True  # exists, just owned by someone else
    except OSError:
        return False
    return True


def _status_fmt_age(seconds: float) -> str:
    seconds = max(0, int(seconds))
    if seconds < 60:
        return f"{seconds}s"
    if seconds < 3600:
        return f"{seconds // 60}m"
    return f"{seconds // 3600}h"


def _status_format_block(snap: dict, now: float) -> str:
    pid = snap.get("pid")
    host = snap.get("host", "?")
    phase = snap.get("phase", "?")
    workers = snap.get("workers") or {}
    current_n = workers.get("current_n", "?")
    pending = snap.get("pending", 0)
    session = snap.get("session") or {}
    ok_n = session.get("ok", 0)
    failed_n = session.get("failed", 0)
    codex = snap.get("codex") or {}
    wk = console._pct(codex.get("weekly_pct"))  # already renders None as "—"
    in_flight = snap.get("in_flight") or []
    age = now - (snap.get("updated_at") or now)
    lines = [f"artpiped {pid} on {host} — {phase} {len(in_flight)}/{current_n}, "
             f"{pending} pending, {ok_n} ok / {failed_n} failed this session, "
             f"codex weekly {wk}  (heartbeat {_status_fmt_age(age)} ago)"]
    for f in in_flight:
        lines.append(f"  {str(f.get('id', '')):<34} {str(f.get('mode', '')):<9} "
                     f"{f.get('elapsed_s', 0)}s / {f.get('timeout_s', 0)}s")
    if snap.get("log_path"):
        lines.append(f"  log: {snap['log_path']}")
    return "\n".join(lines)


def run_status(args: argparse.Namespace) -> int:
    """§7: reads every `<status_dir>/artpiped_*.json`, never touches the
    queue, creates no directories, takes no lock. Exit 0 if at least one
    live daemon, 1 if none, 2 if the directory holds only stale files."""
    try:
        files = sorted(args.status_dir.glob("artpiped_*.json"))
    except OSError:
        files = []

    now = time.time()
    live: list[dict] = []
    stale_removed: list[dict] = []
    for p in files:
        try:
            snap = json.loads(p.read_text())
        except (OSError, ValueError):
            continue
        updated_at = snap.get("updated_at") or 0.0
        if (now - updated_at) > 60.0 and not _status_pid_alive(snap.get("pid")):
            try:
                p.unlink()
            except OSError:
                pass
            stale_removed.append(snap)
            continue
        live.append(snap)

    if getattr(args, "status_json", False):
        print(json.dumps(live, indent=2, sort_keys=True, default=str))
    else:
        if not live and not stale_removed:
            print("no live artpiped daemon")
        for snap in live:
            print(_status_format_block(snap, now))
        for snap in stale_removed:
            age = now - (snap.get("updated_at") or now)
            print(f"artpiped {snap.get('pid')} on {snap.get('host', '?')} — STALE, "
                  f"last heartbeat {_status_fmt_age(age)} ago, pid dead — "
                  f"status file removed")
        if not live and stale_removed:
            print("no live artpiped daemon")

    if live:
        return 0
    if stale_removed:
        return 2
    return 1


def prune_old_scratch_dirs(artsrc_dir: Path, done_dir: Path, failed_dir: Path,
                            max_age_days: float) -> list[str]:
    """Remove `_artsrc/<id>/` scratch directories for jobs that are already
    terminally decided (a manifest exists in `done/` or `failed/`) AND
    whose manifest is at least `max_age_days` old — the PNG has had that
    long to be picked up by whatever consumes it. A dir with NO matching
    manifest is never touched (that job might still be pending, active, or
    simply doesn't correspond to a real job at all) — this only ever
    reclaims space for work that is provably finished and provably old.
    `max_age_days <= 0` disables pruning entirely.
    """
    pruned: list[str] = []
    if max_age_days <= 0:
        return pruned
    cutoff = time.time() - max_age_days * 86400
    try:
        job_dirs = [p for p in artsrc_dir.iterdir() if p.is_dir()]
    except OSError:
        return pruned
    for d in job_dirs:
        job_id = d.name
        manifest = None
        for cand in (done_dir / f"{job_id}.manifest.json", failed_dir / f"{job_id}.manifest.json"):
            if cand.is_file():
                manifest = cand
                break
        if manifest is None:
            continue  # not terminally decided — never prune
        try:
            if manifest.stat().st_mtime >= cutoff:
                continue  # not old enough yet
        except OSError:
            continue
        try:
            shutil.rmtree(d)
            pruned.append(job_id)
        except OSError:
            pass
    return pruned


def _report_batch(console_obj: "console.Console", collapsed_label: str,
                   items: list, detail_of) -> None:
    """§4.4: pruned/repaired/reconciled collapse to one line with a count
    when more than 3 items — the per-id lines still go to the run log
    either way (via `info()`'s own log write when not collapsed, or
    explicitly via `note()` when collapsed)."""
    if not items:
        return
    if len(items) <= 3:
        for item in items:
            console_obj.info(detail_of(item))
    else:
        console_obj.info(collapsed_label)
        for item in items:
            console_obj.note(detail_of(item))


def main(argv=None) -> int:
    args = parse_args(argv)

    # --dry-run promises to touch nothing — ensure_queue_dirs (mkdir) must
    # come AFTER this check, not before it. run_dry_run() itself already
    # wraps its pending_dir.glob() in try/except OSError, so a directory
    # that genuinely doesn't exist yet is handled gracefully rather than
    # requiring mkdir first.
    if args.dry_run:
        return run_dry_run(args)

    # §7: --status is read-only over --status-dir alone — never touches the
    # queue, creates no directories, takes no lock. Returns before
    # ensure_queue_dirs, exactly like --dry-run above.
    if args.status:
        return run_status(args)

    common.ensure_queue_dirs(args.pending_dir, args.active_dir, args.done_dir,
                              args.failed_dir, args.artsrc_dir)

    # ARTPIPE_CONSOLE_REDESIGN_1: RunLog + StatusFile + Console built before
    # anything else prints, so every subsequent line (prune/repair/reconcile
    # included) goes through the same presentation layer, log included —
    # a run that ends in --repair-only/--reconcile-only never starts the
    # renderer thread (there is no long-running loop to render), but still
    # gets a real per-run log and console lines for what it actually did.
    started_at = time.time()
    run_log = console.RunLog.open(args.logs_dir)
    status_file = console.StatusFile(args.status_dir)
    console_obj = console.Console(
        pending_count=lambda: len(_job_files(args.pending_dir)),
        configured_n=args.workers, log=run_log, status=status_file, started_at=started_at)
    console_obj.info(f"artpiped {os.getpid()} — {args.workers} workers, "
                     f"{len(_job_files(args.pending_dir))} pending, log {run_log.path}")

    pruned = prune_old_scratch_dirs(args.artsrc_dir, args.done_dir, args.failed_dir,
                                     args.prune_scratch_days)
    _report_batch(console_obj,
                  f"pruned {len(pruned)} scratch dir(s) older than {args.prune_scratch_days:g}d",
                  pruned, lambda job_id: f"pruned old scratch dir for {job_id}")

    fixed: list[tuple[str, str]] = []
    if args.repair or args.reconcile_only:
        fixed = repair(args.active_dir, args.done_dir, args.failed_dir)
        _report_batch(console_obj, f"repaired {len(fixed)} job(s)",
                      fixed, lambda item: f"repaired {item[0]} — {item[1]}")
        if args.repair and not args.reconcile_only:
            console_obj.info(f"repair-only, {len(fixed)} job(s) completed")
            console_obj.close()
            return 0

    moved = reconcile(args.active_dir, args.pending_dir, args.done_dir,
                       args.failed_dir, args.throughput_log, args.reconcile_min_age)
    _report_batch(console_obj, f"reconciled {len(moved)} job(s)",
                  moved, lambda item: f"reconciled {item[0]} — {item[1]}")

    if args.reconcile_only:
        console_obj.info(f"reconcile-only, {len(moved)} job(s) recovered, "
                         f"{len(fixed)} repaired")
        console_obj.close()
        return 0

    slots: "queue.Queue[int]" = queue.Queue()
    for i in range(args.workers):
        slots.put(i)

    gemini_spent, gemini_skipped_at_start = read_gemini_spend(args.throughput_log)
    gemini_budget = GeminiBudget(args.gemini_budget_usd, args.throughput_log, gemini_spent,
                                  ledger_strict=args.gemini_ledger_strict,
                                  warn=console_obj.warn)
    if gemini_skipped_at_start:
        console_obj.warn(f"throughput.jsonl has {gemini_skipped_at_start} "
                         f"unparseable line(s) at startup")
    if gemini_budget.hard_stop:
        console_obj.warn(f"gemini channel already at/over its ${args.gemini_budget_usd:.2f} "
                         f"budget (${gemini_spent:.2f} spent, per throughput.jsonl) — gemini "
                         f"jobs will not be claimed this run")

    # CODEX_UAC_STORM_1: one fingerprint check, before ANY worker home is
    # leased — never per-slot, never per-job. A stale/missing seed template
    # otherwise lets each of N workers independently discover the problem by
    # each triggering its own (possibly unattended) UAC prompt. On a
    # mismatch the codex channel is refused for this whole run (never
    # rechecked — recapturing the template needs a fresh daemon start); the
    # gemini channel is entirely unaffected.
    codex_sandbox_ok, codex_sandbox_msg = common.codex_sandbox_preflight(args.codex_sandbox_base)
    if codex_sandbox_ok:
        console_obj.info(f"codex sandbox ok — {codex_sandbox_msg}")
    else:
        console_obj.warn(f"codex channel disabled for this run — {codex_sandbox_msg}")
        console_obj.mark_codex_channel_disabled()

    # codex_home leases are NOT acquired here — RunCtx acquires each slot's
    # lease lazily, on that slot's first CODEX job (see codex_home_for_slot).
    # A run that only ever processes gemini jobs therefore never creates a
    # single codex_home directory.
    ctx = RunCtx(args.worker_script, args.validator_script, args.manifest_schema,
                 args.artsrc_dir, args.active_dir, args.codex_home_root, args.workers,
                 args.timeout_generate, args.timeout_edit, args.reasoning_effort,
                 args.verbose, slots, args.gemini_worker_script, args.gemini_timeout,
                 throughput_log=args.throughput_log)
    detector = Detector()
    stop_event = threading.Event()
    render_stop = threading.Event()

    def _render_loop():
        while not render_stop.is_set():
            console_obj.tick()
            render_stop.wait(0.25)

    render_thread = threading.Thread(target=_render_loop, daemon=True, name="artpiped-console")
    render_thread.start()

    futures: dict = {}  # future -> (job_path, channel, reserved_usd) — bound before
                        # _handle_signal so its closure sees the real, live dict

    def _handle_signal(signum, _frame):
        console_obj.info(f"signal {signum} received — draining {len(futures)} "
                         f"in-flight jobs, then exiting")
        stop_event.set()

    signal.signal(signal.SIGTERM, _handle_signal)
    signal.signal(signal.SIGINT, _handle_signal)

    def _channel_permanently_blocked(ch: str) -> bool:
        if ch == "gemini":
            return gemini_budget.admission_blocked()
        return (not codex_sandbox_ok) or detector.admission_blocked()

    last_meter_refresh = 0.0

    try:
        with ThreadPoolExecutor(max_workers=args.workers) as pool:
            while True:
                if not stop_event.is_set():
                    while len(futures) < args.workers:
                        codex_in_flight = sum(1 for _, ch, _r in futures.values() if ch == "codex")
                        current_codex_n = detector.current_n(args.workers)

                        def _claim_blocked(ch, _in_flight=codex_in_flight, _cap=current_codex_n):
                            if ch == "gemini":
                                return gemini_budget.admission_blocked()
                            return ((not codex_sandbox_ok) or detector.admission_blocked()
                                    or _in_flight >= _cap)

                        job_path = claim_next(args.pending_dir, args.active_dir,
                                              channel_blocked=_claim_blocked)
                        if job_path is None:
                            break
                        ch = _channel_of(job_path)
                        reserved_usd = 0.0
                        if ch == "gemini":
                            # Reserve the CONSERVATIVE estimate right now,
                            # before this job ever runs — closes the race
                            # where N claims in the same instant (none has
                            # reported a real cost back yet) could
                            # collectively overshoot the cap by up to N-1
                            # jobs' worth. admission_blocked() and reserve()
                            # now share ONE predicate (_would_fit), so this
                            # should always succeed given _claim_blocked's
                            # own check moments ago — but a fresh
                            # cross-process spend landing in that tiny gap
                            # is possible, and a job is NEVER run unreserved:
                            # if reserve() genuinely refuses, the claim is
                            # returned to pending/ (never "proceed anyway"),
                            # and this inner loop stops for this pass rather
                            # than risking a tight reclaim/fail loop.
                            if gemini_budget.reserve(GEMINI_RESERVE_ESTIMATE_USD):
                                reserved_usd = GEMINI_RESERVE_ESTIMATE_USD
                            else:
                                dest = args.pending_dir / job_path.name
                                if not dest.exists():
                                    try:
                                        os.rename(job_path, dest)
                                    except FileNotFoundError:
                                        pass
                                console_obj.warn(
                                    f"claimed {job_path.name} as gemini but the "
                                    f"reservation was refused moments later (a fresh "
                                    f"cross-process spend landed in between) — returned "
                                    f"to pending/, never run unreserved")
                                break
                        mode = _mode_of(job_path)
                        timeout_s = (args.gemini_timeout if ch == "gemini"
                                     else (args.timeout_edit if mode == "edit"
                                           else args.timeout_generate))
                        console_obj.job_started(job_path.stem, mode, ch, timeout_s)
                        futures[pool.submit(process_job, job_path, ctx)] = (job_path, ch, reserved_usd)

                # Finding 4: an independent meter refresh. note_meters()'s
                # only OTHER caller is finalize_job of a COMPLETING codex
                # job — but admission_blocked() then refuses to let any
                # NEW codex job be claimed while refuse_new/stop_all is
                # set, so without this, nothing would ever call
                # note_meters() again and the wedge would last until the
                # daemon is restarted. Cheap to skip: gated on the
                # interval, on actually being blocked, on a codex_home
                # already existing to read (no job needed — read_meters()
                # just reads whatever rollout is already on disk), and on
                # there being codex work actually waiting on this wedge.
                if (detector.refuse_new or detector.stop_all) and not stop_event.is_set():
                    now_mono = time.monotonic()
                    if now_mono - last_meter_refresh >= args.meter_refresh_interval:
                        last_meter_refresh = now_mono
                        home = ctx.any_leased_codex_home()
                        if home is not None and _codex_jobs_pending(args.pending_dir):
                            detector.note_meters(codex_grumpiness.read_meters(home),
                                                  warn=console_obj.warn)
                            console_obj.quota(quota_state(detector, args.workers))

                if not futures:
                    exhausted = (_queue_empty(args.pending_dir) or
                                not _any_claimable(args.pending_dir, _channel_permanently_blocked))
                    if stop_event.is_set() or (args.once and exhausted):
                        break
                    time.sleep(args.poll_interval)
                    continue

                done, _ = wait(list(futures.keys()), timeout=args.poll_interval,
                               return_when=FIRST_COMPLETED)
                for fut in done:
                    job_path, ch, reserved_usd = futures.pop(fut)
                    try:
                        result = fut.result()
                    except Exception as exc:  # never let a worker-thread crash kill the daemon
                        # `ch` is what claim_next() actually claimed THIS
                        # job as — preserved here even though process_job
                        # now wraps its own dispatch and structurally
                        # should never let this fire for a channel mismatch
                        # any more. Belt and suspenders: a bare "codex"
                        # default here (the old behaviour) is exactly what
                        # let a real gemini spend get billed as $0 codex.
                        result = {"id": job_path.stem, "channel": ch, "status": "failed",
                                  "cost_usd": 0.0, "worker_status": "daemon_error",
                                  "validator": "not_run",
                                  "note": f"process_job raised: {type(exc).__name__}: {exc}"}
                    finalize_job(job_path, result, args.done_dir, args.failed_dir,
                                 args.active_dir, args.throughput_log, detector,
                                 gemini_budget, args.workers, reserved_usd,
                                 console_obj=console_obj)

                if stop_event.is_set() and not futures:
                    break
                if args.once and not futures and _queue_empty(args.pending_dir):
                    break
    finally:
        for fh in ctx.lease_handles:
            try:
                fh.close()
            except OSError:
                pass
        render_stop.set()
        render_thread.join(timeout=1.0)

    # Exit nonzero IFF work actually remains — never merely because a wedge
    # occurred at some point during the run. `hard_stop`/`stop_all`/a
    # gemini budget hard-stop are worth REPORTING (Console.stopped()'s own
    # parenthetical still names the reason honestly), but a wedge whose
    # queue nonetheless drained clean (nothing left pending) is not
    # abandonment — reporting it as one is a claim the actual queue state
    # doesn't back up.
    #
    # Deliberately pending/ ALONE, not active/ too: active/ is SHARED
    # between concurrent daemons, and a job sitting there might be another
    # daemon's perfectly healthy in-flight claim, not this daemon's own
    # abandoned work — checking it here raced exactly that way in testing
    # (one of two daemons in a clean 2-daemon/10-job run saw the OTHER
    # daemon's still-processing job in active/ and wrongly reported
    # "work remains"). pending/ has no such ambiguity: a file is either
    # still there (unclaimed) or it isn't, full stop.
    pending_remaining_n = len(_job_files(args.pending_dir))
    work_remains = pending_remaining_n > 0
    exit_code = 1 if work_remains else 0
    console_obj.stopped(pending_remaining_n, work_remains)
    console_obj.close()
    return exit_code


if __name__ == "__main__":
    sys.exit(main())
