def _coerce_epoch(value) -> float | None:
    """`primary_resets_at` must be a numeric unix epoch. Anything else (an
    ISO string, a seconds-remaining delta, None) is coerced to "unknown"
    rather than trusted: an ISO string would TypeError the main thread
    comparing `time.time() < sleep_until`, and a seconds-remaining value
    would compare as a tiny past epoch and silently never sleep at all —
    both worse than falling back to a value we know is safe."""
    if isinstance(value, bool):
        return None
    if isinstance(value, (int, float)):
        return float(value)
    return None


class Detector:
    """All shared admission-control state for the CODEX channel only — the
    gemini channel is gated by GeminiBudget instead (spec: "the codex
    grumpiness detector does NOT gate gemini jobs"). Touched ONLY from the
    main thread, after a job's future has completed — never from a worker
    thread — so it needs no lock of its own.

    De-escalating by design, except row 1: every threshold here is
    RECOMPUTED from the CURRENT reading on each note_meters() call, so a
    weekly usage that climbed to 93% and then reset to 1% (a new week, or a
    stale one-off bad reading) clears refuse_new/n_override/sleep_until on
    the very next healthy reading. Only `hard_stop` (row 1, an explicit
    TooManyRequests) stays latched for the rest of this run — a real
    throttle refusal is not something a later healthy meter reading should
    be allowed to paper over.
    """

    def __init__(self):
        self.hard_stop = False       # row 1: TooManyRequests — LATCHED, never clears
        self.refuse_new = False      # row 2 @ weekly >= 90 — recomputed each reading
        self.stop_all = False        # row 2 @ weekly >= 97 — recomputed each reading
        self.warn_logged = False     # row 2 @ weekly >= 80 — clears below 80 so it can re-fire
        self.n_override = None       # row 3 @ 5h >= 70 -> N=1 — recomputed each reading
        self.sleep_until = None      # row 3 @ 5h >= 90 -> sleep to resets_at — recomputed
        self.wall_clock_history: list[float] = []
        self._slow_streak = 0
        self.effective_n = None      # row 4: halved on a sustained slowdown (one-way ratchet)

    def note_rate_limited(self) -> None:
        self.hard_stop = True

    def note_meters(self, meters: dict | None) -> None:
        """`meters` is codex_grumpiness.read_meters()'s own return shape —
        `{"ok": bool, "secondary_used_percent":.., "primary_used_percent":..,
        "primary_resets_at":..}` — not a raw rate_limits object. `ok: False`
        (no rollout yet, or none new enough) is ignorance: state is left
        UNCHANGED, neither reset to healthy nor held at whatever it was."""
        if not meters or not meters.get("ok"):
            return
        weekly = meters.get("secondary_used_percent")
        five_h = meters.get("primary_used_percent")
        resets_raw = meters.get("primary_resets_at")

        if weekly is not None:
            self.stop_all = weekly >= WEEKLY_STOP
            self.refuse_new = (not self.stop_all) and weekly >= WEEKLY_REFUSE
            if weekly >= WEEKLY_WARN:
                if not self.warn_logged:
                    print(f"artpiped: WARNING weekly Codex usage at {weekly:.0f}% "
                          f"(row 2, warn threshold {WEEKLY_WARN:.0f})", file=sys.stderr)
                    self.warn_logged = True
            else:
                self.warn_logged = False  # de-escalate: a fresh low reading can warn again later

        if five_h is not None:
            if five_h >= FIVE_H_SLEEP:
                coerced = _coerce_epoch(resets_raw)
                if coerced is not None:
                    self.sleep_until = coerced
                    self.n_override = None
                else:
                    print(f"artpiped: WARNING primary_resets_at is not a usable epoch "
                          f"({resets_raw!r}) — five-hour usage is >= {FIVE_H_SLEEP:.0f}% "
                          f"but falling back to N=1 instead of a sleep gate I cannot trust",
                          file=sys.stderr)
                    self.sleep_until = None
                    self.n_override = 1
            elif five_h >= FIVE_H_DROP_N1:
                self.n_override = 1
                self.sleep_until = None
            else:
                self.n_override = None
                self.sleep_until = None

    def note_wall_clock(self, seconds: float, configured_n: int) -> None:
        """Row 4 spec, literally: the ROLLING MEDIAN of the last 5 wall-clock
        readings, checked against 2x baseline, for 3 CONSECUTIVE calls —
        not "the last 3 readings were each individually slow". A single
        outlier (one very slow request among four fast ones) moves the
        median far less than it would move a naive "all of the last 3"
        check, which is the point of using a median here at all.

        Timeouts DO reach this method, correctly: a timed-out request is
        definitionally the slowest possible one, and this row's job is to
        notice a sustained slowdown, timeouts included. What must NEVER
        reach note_rate_limited (row 1) is a plain timeout — only an
        explicit TooManyRequests/rate-limited text match does that (see
        _looks_rate_limited and its call site) — so a slow-but-real request
        cannot masquerade as a throttle refusal, even though it is exactly
        the kind of thing that SHOULD slow this row down.
        """
        self.wall_clock_history.append(seconds)
        self.wall_clock_history = self.wall_clock_history[-5:]
        median = statistics.median(self.wall_clock_history)
        if median > BASELINE_WALL_CLOCK_S * WALL_CLOCK_MULTIPLIER:
            self._slow_streak += 1
        else:
            self._slow_streak = 0
        if self._slow_streak >= WALL_CLOCK_STREAK:
            base = self.effective_n if self.effective_n is not None else configured_n
            self.effective_n = max(1, base // 2)
            self._slow_streak = 0  # don't re-trigger every single tick thereafter

    def admission_blocked(self) -> bool:
        if self.hard_stop or self.stop_all or self.refuse_new:
            return True
        if self.sleep_until and time.time() < self.sleep_until:
            return True
        return False

    def current_n(self, configured_n: int) -> int:
        n = configured_n
        if self.n_override is not None:
            n = min(n, self.n_override)
        if self.effective_n is not None:
            n = min(n, self.effective_n)
        return max(1, n)


