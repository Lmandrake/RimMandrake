def _priority_of(path: Path) -> int:
    try:
        return int(json.loads(path.read_text()).get("priority", 100))
    except (OSError, ValueError, TypeError):
        return 100


def _channel_of(path: Path) -> str:
    try:
        ch = json.loads(path.read_text()).get("channel") or "codex"
        return ch if isinstance(ch, str) else "codex"
    except (OSError, ValueError, TypeError):
        return "codex"


def claim_next(pending_dir: Path, active_dir: Path, channel_blocked=None) -> Path | None:
    """Atomic claim = rename pending/<id>.json -> active/<id>.json.

    `os.rename` removing the SOURCE is the atomic event: if another daemon
    renamed it away between our glob() and our rename(), the source is gone
    and rename raises FileNotFoundError — that daemon lost the race, moves on
    to the next candidate, and never touches the file the winner claimed.

    `channel_blocked(channel_str) -> bool`, if given, skips a candidate
    whose channel is currently gated (codex admission-blocked, or the
    gemini budget hard-stopped) WITHOUT skipping other candidates of the
    other channel — so a wedged codex account never stalls gemini jobs
    still sitting in the same queue, and vice versa.

    Two things happen right after a successful rename, both load-bearing:

    1. `os.utime(dest)` stamps a FRESH mtime. `os.rename` preserves the
       inode's existing mtime, so without this a job that sat in pending/
       for 20 minutes before being claimed would carry that 20-minute-old
       timestamp straight into active/ — and reconcile()'s age gate, which
       exists specifically to tell a crashed orphan from a live claim by
       age, would misread a job claimed one second ago as one stale enough
       to steal back.
    2. A re-stat of `dest` immediately after the rename, because production
       runs on /mnt/d (DrvFs/9p) — see `common.py`'s module docstring.
       Treating a stat that can't see what we just renamed as a lost race —
       the same as a FileNotFoundError on the rename itself — is the best
       mitigation available from user space; it is a mitigation, not a proof.
    """
    try:
        candidates = sorted(pending_dir.glob("*.json"), key=lambda p: (_priority_of(p), p.name))
    except OSError:
        return None
    for src in candidates:
        if channel_blocked is not None and channel_blocked(_channel_of(src)):
            continue
        dest = active_dir / src.name
        if dest.exists():
            continue  # a stray same-named file already claimed — never clobber it
        try:
            os.rename(src, dest)
        except FileNotFoundError:
            continue  # lost the race to another daemon
        try:
            os.utime(dest, None)
            dest.stat()
        except FileNotFoundError:
            continue  # a stale-read filesystem's rename that a stat can't see: lost race
        return dest
    return None


def _queue_empty(pending_dir: Path) -> bool:
    try:
        next(pending_dir.glob("*.json"))
        return False
    except StopIteration:
        return True


def _job_files(dir_path: Path) -> list[Path]:
    """Every REAL job file directly in `dir_path` — never a
    `<id>.worker_last_message.json` sidecar. That sidecar also ends in
    `.json`, so a naive `*.json` glob over `active/` matches it too;
    `reconcile()`/`repair()` used to then treat it as a phantom job (its
    `.stem` is `<id>.worker_last_message`, a bogus id that no manifest will
    ever exist for), promoting it to `pending/` where it gets claimed,
    fails common.load_job's required-field check, and is written into
    throughput.jsonl as a fake failed job."""
    try:
        return sorted(p for p in dir_path.glob("*.json")
                      if not p.name.endswith(".worker_last_message.json"))
    except OSError:
        return []


def _any_claimable(pending_dir: Path, channel_blocked) -> bool:
    """True if pending/ holds at least one job whose channel is not
    currently blocked — used to tell "genuinely nothing left to do" apart
    from "something's left, but every channel that could claim it is
    blocked right now", which used to hang --once forever whenever codex
    was wedged but unrelated gemini jobs (not blocked at all) were still
    sitting in the same queue: the old exhaustion check only looked at
    whether the (single) Detector was blocked, so a healthy gemini channel
    could never end the loop on its own."""
    try:
        for p in pending_dir.glob("*.json"):
            if not channel_blocked(_channel_of(p)):
                return True
    except OSError:
        pass
    return False


def reconcile(active_dir: Path, pending_dir: Path, done_dir: Path,
              failed_dir: Path, min_age_s: float = 600.0) -> list[tuple[str, str]]:
    """Crash recovery: an active/ job with no manifest anywhere MIGHT be an
    orphan from a killed daemon — or it might just be another live daemon's
    in-flight claim, which looks IDENTICAL (no manifest yet either) until it
    finishes. The only honest signal that distinguishes them is age: no
    single job can legitimately still be running past its own worst-case
    ceiling (an edit's --timeout-edit + the subprocess grace + the
    validator's own timeout + one row-1 retry), so `min_age_s` defaults
    comfortably above that. A job younger than this is left alone even with
    no manifest.

    A DIFFERENT crash state — active/<id>.json AND a matching
    done/failed/<id>.manifest.json BOTH exist, meaning the daemon wrote the
    manifest and died before moving the job file — is deliberately left
    alone here too (see the `continue` below): reconcile()'s job is telling
    a live claim from an orphan, not completing an already-decided outcome.
    `repair()` is the tool for that.
    """
    moved = []
    actives = _job_files(active_dir)
    now = time.time()
    for p in actives:
        job_id = p.stem
        if (done_dir / f"{job_id}.manifest.json").is_file() or \
           (failed_dir / f"{job_id}.manifest.json").is_file():
            # Already terminally decided, just not moved — repair()'s job,
            # not reconcile()'s: guessing which of two manifests (if there
            # were ever two) is authoritative is worse than asking. Still
            # clean up the last-message stray here too, so this state
            # doesn't also leave litter behind while it waits for repair().
            stray = active_dir / f"{job_id}.worker_last_message.json"
            if stray.is_file():
                try:
                    stray.unlink()
                except OSError:
                    pass
            continue
        try:
            age = now - p.stat().st_mtime
        except OSError:
            continue
        if age < min_age_s:
            continue  # too young to be confidently orphaned — may be live
        dest = pending_dir / p.name
        if dest.exists():
            continue
        try:
            os.rename(p, dest)
        except FileNotFoundError:
            continue
        try:
            dest.stat()
        except FileNotFoundError:
            continue  # see claim_next()'s docstring: a stale-read mount can
                      # report a rename a stat then can't see — lost race, not a move.
        moved.append((job_id, "no manifest in done/ or failed/"))
        stray = active_dir / f"{job_id}.worker_last_message.json"
        if stray.is_file():
            try:
                stray.unlink()
            except OSError:
                pass
    return moved


def repair(active_dir: Path, done_dir: Path, failed_dir: Path) -> list[tuple[str, str]]:
    """Complete the crash state reconcile() deliberately leaves alone: an
    active/<id>.json that's still sitting there because the daemon died
    between writing done/<id>.manifest.json (or failed/) and moving the job
    file — one, unambiguous manifest already says the outcome, so finishing
    the move is not a guess. If manifests exist on BOTH sides (should never
    happen — a job is filed to exactly one target directory — but if it
    does, that IS genuinely ambiguous) this leaves it alone for a human.
    """
    repaired = []
    for p in _job_files(active_dir):
        job_id = p.stem
        done_manifest = done_dir / f"{job_id}.manifest.json"
        failed_manifest = failed_dir / f"{job_id}.manifest.json"
        if done_manifest.is_file() and failed_manifest.is_file():
            continue  # genuinely ambiguous — leave for a human
        if done_manifest.is_file():
            target_dir = done_dir
        elif failed_manifest.is_file():
            target_dir = failed_dir
        else:
            continue  # no manifest anywhere — that's reconcile()'s job, not repair's
        dest = target_dir / p.name
        if dest.exists():
            continue
        try:
            os.rename(p, dest)
        except FileNotFoundError:
            continue
        try:
            dest.stat()
        except FileNotFoundError:
            continue
        repaired.append((job_id, f"completed the move into {target_dir.name}/ "
                                  f"(its manifest already existed there)"))
        stray = active_dir / f"{job_id}.worker_last_message.json"
        if stray.is_file():
            try:
                stray.unlink()
            except OSError:
                pass
    return repaired


