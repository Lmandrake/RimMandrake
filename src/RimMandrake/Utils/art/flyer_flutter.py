#!/usr/bin/env python3
"""flyer_flutter.py - a chaotic, whole-body flutter flip-book from a kept static, for a flyer with no wings.

RIMMANDRAKE_REDRAW_SKINFLAP_FLUTTER_BUTTERFLY_NOT_SAME_PICTURE. Owner, 2026-11-27, of the Skinflap: "the creature
doesn't resemble anything with wings at all. There is a chaotic butterfly flying effect that is likely a much better
fit to what such a creature would do than an orderly flapping motion." So this recipe is the opposite of
flyer_cutout.py (whose body plate stays pixel-identical while two wing layers turn): here the WHOLE body moves in
every frame. It is for a def the owner took out of the body-lock rule (flyer_gate.WHOLE_BODY); a winged flyer keeps
flyer_cutout.

The motion, per frame, in the order the pixels are mapped:
  - a jump: a quick, irregular change of height and of side position (the butterfly's erratic path, baked into the
    frame because the generated flight AnimationDef carries no per-keyframe offset);
  - a bank: a turn of the whole sheet about its centre;
  - a fold: the sheet closes about its middle line, as a butterfly's wings meet, and its outer parts rise; how far it
    closes changes irregularly from frame to frame, never in a regular beat;
  - a curl: the sheet cups up or down (side view: east);
  - a billow: two slow ripples run across the whole sheet with a new phase each frame;
  - shade: the half that folds away from the light darkens a little.
Every parameter comes from a seeded generator in the set's JSON, so a build is reproducible byte for byte. A sequence
is drawn again until every pair of neighbouring frames (the loop's last and first included) differs by a jump or a
bank of the set's minimum size: the change is quick, never a slow drift.

Nothing is generated by a model and nothing is repainted: every pixel is a pixel of the kept static, moved. The canvas
is larger than the static (a margin for the jumps); the def's flyingAnimationDrawSize multiplier must be canvas/static
so that the drawing keeps its size (selftest_skinflap_flutter.py checks the def).

Config flyer_flutter_sets/<Set>.json:
  {"set", "folder", "static" (the static's file stem in folder), "prefix", "frames", "canvas", "seed",
   "jump_x", "jump_up", "jump_down" (px on the canvas), "bank" (deg), "fold" [min, max] (width kept, 1 = open),
   "lift" (px the outer edge rises at a full fold), "curl" (px), "billow" (px), "billow_wave" (px), "shade",
   "min_jump" (px), "min_bank" (deg), "facings": {"east": {"fold_scale": f, "curl_scale": c}, ...}}

Verbs:
  build CONFIG --out DIR      write <prefix><N>_<facing>.png for every facing (never into src/: install is art.py)
  params CONFIG               print the per-frame parameters
Exit 0 = written, 2 = bad input.
"""
from __future__ import annotations

import argparse
import json
import math
import random
import sys
from pathlib import Path

import numpy as np
from PIL import Image

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[3]
SETS = HERE / "flyer_flutter_sets"
FACINGS = ("east", "north", "south")
MAX_DRAWS = 2000       # hang guard on the sequence redraw: a set whose minimums cannot be met fails by name


def frame_params(cfg: dict) -> list[dict]:
    """The per-frame parameters, shared by every facing so the facings move as one creature."""
    rng = random.Random(cfg["seed"])
    n = cfg["frames"]
    lo, hi = cfg["fold"]
    for _ in range(MAX_DRAWS):
        ps = []
        for _k in range(n):
            ps.append({
                "tx": rng.uniform(-cfg["jump_x"], cfg["jump_x"]),
                "ty": rng.uniform(-cfg["jump_up"], cfg["jump_down"]),     # image y grows down: negative is up
                "rot": rng.uniform(-cfg["bank"], cfg["bank"]),
                "fold": rng.uniform(lo, hi) if rng.random() < 0.65 else rng.uniform(lo, lo + (hi - lo) * 0.35),
                "curl": rng.uniform(-1.0, 1.0),
                "squash": rng.uniform(0.88, 1.10),
                "ph1": rng.uniform(0, 2 * math.pi), "ph2": rng.uniform(0, 2 * math.pi),
            })
        quick = all(
            math.hypot(ps[k]["tx"] - ps[k - 1]["tx"], ps[k]["ty"] - ps[k - 1]["ty"]) >= cfg["min_jump"]
            or abs(ps[k]["rot"] - ps[k - 1]["rot"]) >= cfg["min_bank"]
            for k in range(n))
        folds = sorted(p["fold"] for p in ps)
        if quick and folds[0] < lo + 0.1 * (hi - lo) and folds[-1] > hi - 0.15 * (hi - lo):
            return ps
    raise SystemExit(f"{cfg['set']}: no sequence of {n} frames meets min_jump/min_bank in {MAX_DRAWS} draws")


def sample(src: np.ndarray, xs: np.ndarray, ys: np.ndarray) -> np.ndarray:
    """Bilinear sample of premultiplied RGBA at float coordinates; outside the image is transparent."""
    h, w = src.shape[:2]
    x0, y0 = np.floor(xs).astype(int), np.floor(ys).astype(int)
    fx, fy = (xs - x0)[..., None], (ys - y0)[..., None]
    out = np.zeros(xs.shape + (4,), dtype=np.float64)
    for dx, dy, wt in ((0, 0, (1 - fx) * (1 - fy)), (1, 0, fx * (1 - fy)), (0, 1, (1 - fx) * fy), (1, 1, fx * fy)):
        xi, yi = x0 + dx, y0 + dy
        ok = (xi >= 0) & (xi < w) & (yi >= 0) & (yi < h)
        v = np.zeros(xs.shape + (4,))
        v[ok] = src[yi[ok], xi[ok]]
        out += v * wt
    return out


def render(static: Image.Image, cfg: dict, facing: str, p: dict) -> Image.Image:
    fcfg = cfg["facings"].get(facing, {})
    fold_scale, curl_scale = fcfg.get("fold_scale", 1.0), fcfg.get("curl_scale", 1.0)
    s = np.asarray(static.convert("RGBA")).astype(np.float64)
    a = s[..., 3:4] / 255.0
    pre = np.concatenate([s[..., :3] * a, s[..., 3:4]], axis=2)      # premultiplied: no dark halo at the edge
    hs, ws = s.shape[:2]
    ys_, xs_ = np.nonzero(s[..., 3] > 128)
    cx, cy = xs_.mean(), ys_.mean()                                   # the body's centre in the static
    half = max(cx - xs_.min(), xs_.max() - cx)
    C = cfg["canvas"]
    yy, xx = np.mgrid[0:C, 0:C].astype(np.float64)
    # inverse map, destination -> static: undo the jump, then the bank, then the fold, the curl and the billow
    u = xx - (C / 2 + p["tx"])
    v = yy - (C / 2 + p["ty"])
    r = math.radians(p["rot"])
    ur = u * math.cos(r) + v * math.sin(r)
    vr = -u * math.sin(r) + v * math.cos(r)
    fold = 1.0 - (1.0 - p["fold"]) * fold_scale
    su = ur / fold                                                    # the sheet closes about its middle line
    reach = np.clip(np.abs(su) / half, 0, 1.5)
    sv = vr / p["squash"]
    sv = sv + cfg["lift"] * (1.0 - fold) * reach ** 1.5                # the outer parts rise as it closes
    sv = sv + cfg["curl"] * curl_scale * p["curl"] * (reach ** 2 - 0.35)
    lam = cfg["billow_wave"]
    su = su + cfg["billow"] * np.sin(2 * math.pi * sv / lam + p["ph1"])
    sv = sv + cfg["billow"] * np.sin(2 * math.pi * su / (lam * 1.3) + p["ph2"])
    out = sample(pre, su + cx, sv + cy)
    # shade: the half turned away from the light darkens with the fold
    side = np.where(su > 0, 1.0, 0.0) if p["rot"] >= 0 else np.where(su < 0, 1.0, 0.0)
    k = 1.0 - cfg["shade"] * (1.0 - fold) * side * np.clip(reach, 0, 1)
    out[..., :3] *= k[..., None]
    al = out[..., 3:4]
    rgb = np.where(al > 0, out[..., :3] / np.maximum(al, 1e-9) * 255.0, 0)
    img = np.concatenate([np.clip(rgb, 0, 255), np.clip(al, 0, 255)], axis=2).round().astype(np.uint8)
    img[img[..., 3] == 0] = 0
    return Image.fromarray(img, "RGBA")


def load(config: str) -> dict:
    p = Path(config)
    if not p.is_file():
        p = SETS / f"{config}.json"
    if not p.is_file():
        raise SystemExit(2)
    return json.loads(p.read_text())


def build(cfg: dict, out: Path) -> list[Path]:
    out.mkdir(parents=True, exist_ok=True)
    ps = frame_params(cfg)
    written = []
    for f in FACINGS:
        static = Image.open(REPO / cfg["folder"] / f"{cfg['static']}_{f}.png")
        for k, p in enumerate(ps, start=1):
            path = out / f"{cfg['prefix']}{k}_{f}.png"
            render(static, cfg, f, p).save(path, optimize=True)
            written.append(path)
    return written


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    sub = ap.add_subparsers(dest="verb", required=True)
    b = sub.add_parser("build")
    b.add_argument("config")
    b.add_argument("--out", required=True)
    sub.add_parser("params").add_argument("config")
    a = ap.parse_args()
    cfg = load(a.config)
    if a.verb == "params":
        for k, p in enumerate(frame_params(cfg), start=1):
            print(k, {key: round(v, 2) for key, v in p.items()})
        return 0
    out = Path(a.out).resolve()
    if (REPO / "src").resolve() in out.parents and "Textures" in out.parts:
        print("refused: build writes outside src Textures; install is art.py install", file=sys.stderr)
        return 2
    for p in build(cfg, out):
        print(p)
    return 0


if __name__ == "__main__":
    sys.exit(main())
