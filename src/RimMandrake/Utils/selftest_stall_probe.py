    ("enter_drops_tick", "probe", "internal static void Enter(TickList l, int tick) { CurTick = tick; CurTickList = l; }",
     "internal static void Enter(TickList l, int tick) { CurTickList = l; }", "ProbeBucketByEnteredTick"),
    ("tlpre_enters_live_minus_one", "profiler", "JawaBenchStallProbe.Enter(__instance, Find.TickManager.TicksGame);",
     "JawaBenchStallProbe.Enter(__instance, Find.TickManager.TicksGame - 1);", "ProbeBucketByEnteredTick"),
