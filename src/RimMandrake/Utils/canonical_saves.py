#!/usr/bin/env python3
"""canonical_saves.py - the companion's list of canonical world saves, made from infrastructure/state/CANONICAL_SAVE.md.

    python3 src/RimMandrake/Utils/canonical_saves.py show     the list the document gives
    python3 src/RimMandrake/Utils/canonical_saves.py check    0 the committed list is that list, 1 it is not (each
                                                              difference named), 3 the document could not be read
    python3 src/RimMandrake/Utils/canonical_saves.py write    write the generated file

The rule and its promises: design/specs/2026-11-23-canonical-save-guard/boundary.md. bridgetools/build.py calls write().
A document that cannot be read is Unreadable, never an empty list, and nothing is written."""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
DOC = "infrastructure/state/CANONICAL_SAVE.md"
GENERATED = "src/RimMandrake/bridgetools/JawaBench.BridgeTools/JawaBenchCanonicalSaves.cs"
_BLOCK = re.compile(r"^```guard[ \t]*\n(.*?)^```[ \t]*$", re.M | re.S)
_LINE = re.compile(r"^[A-Za-z0-9_][A-Za-z0-9_.\- ]*\*?$")
# a complete save file name in the prose; `<name>.rws.bak-...` is a backup, and `...R3.rws` (a name cut short) is not a name
_NAMED = re.compile(r"(?<![\w.\-*…])([A-Za-z0-9_](?:[\w.\-]*?[\w\-])?)\.rws(?!\.bak|\w)")


class Unreadable(Exception):
    """The document could not be read as a list: the cause, by name."""


def rule(text):
    """-> (names, starts): the guarded save names and the guarded name starts, sorted."""
    blocks = _BLOCK.findall(text)
    if len(blocks) != 1:
        raise Unreadable("%s has %d ```guard blocks, expected one" % (DOC, len(blocks)))
    names, starts = set(), set()
    for ln in (x.strip() for x in blocks[0].splitlines()):
        if not ln:
            continue
        if not _LINE.match(ln) or ln.lower().endswith((".rws", ".rws*")):
            raise Unreadable("%s: %r in the guard block is not a save name (no .rws, no path; * only at the end)" % (DOC, ln))
        (starts if ln.endswith("*") else names).add(ln.rstrip("*"))
    if not names:
        raise Unreadable("%s: the guard block names no save" % DOC)
    names.update(_NAMED.findall(text))
    return sorted(names), sorted(starts)


def read(repo=REPO):
    p = os.path.join(repo, *DOC.split("/"))
    try:
        with open(p, encoding="utf-8") as f:
            text = f.read()
    except (OSError, UnicodeDecodeError) as e:
        raise Unreadable("%s could not be read: %s" % (p, e))
    return rule(text)


def source(names, starts):
    """The text of the generated C# file."""
    def arr(xs):
        return "".join('            "%s",\n' % x for x in xs)
    return ("// GENERATED by src/RimMandrake/Utils/canonical_saves.py from %s. Do not edit: edit the document, then\n"
            "// run `python3 src/RimMandrake/Utils/canonical_saves.py write`. Rules: design/specs/2026-11-23-canonical-save-guard/boundary.md\n"
            "namespace JawaBench.BridgeTools\n{\n    internal static class JawaBenchCanonicalSaves\n    {\n"
            "        internal static readonly string[] Names =\n        {\n%s        };\n\n"
            "        /// <summary>The start of a name: every save whose name starts with one is guarded.</summary>\n"
            "        internal static readonly string[] Starts =\n        {\n%s        };\n    }\n}\n"
            % (DOC, arr(names), arr(starts)))


def committed(repo=REPO):
    """-> the generated file's text, or None when it is absent."""
    try:
        with open(os.path.join(repo, *GENERATED.split("/")), encoding="utf-8") as f:
            return f.read()
    except FileNotFoundError:
        return None


def problems(doc_text, generated_text):
    """-> every way the generated file is not what the rule reads in the document ([] = it is)."""
    names, starts = rule(doc_text)
    if generated_text is None:
        return ["%s is absent" % GENERATED]
    if generated_text == source(names, starts):
        return []
    lacks = [n for n in names + starts if '"%s"' % n not in generated_text]
    return (["the companion's list lacks %s, which %s names" % (n, DOC) for n in lacks]
            or ["%s is not what the rule writes (an extra name or another edit)" % GENERATED])


def write(repo=REPO):
    """Write the generated file when it differs. -> True when it was written."""
    want = source(*read(repo))
    if committed(repo) == want:
        return False
    with open(os.path.join(repo, *GENERATED.split("/")), "w", encoding="utf-8", newline="\n") as f:
        f.write(want)
    return True


def main(argv):
    cmd = argv[0] if argv else ""
    if cmd not in ("show", "check", "write"):
        print(__doc__)
        return 2
    try:
        names, starts = read()
        if cmd == "show":
            print("\n".join(names + [s + "*" for s in starts]))
            return 0
        if cmd == "write":
            print("written: %s" % GENERATED if write() else "already current: %s" % GENERATED)
            return 0
        with open(os.path.join(REPO, *DOC.split("/")), encoding="utf-8") as f:
            bad = problems(f.read(), committed())
    except Unreadable as e:
        print("UNREADABLE: %s" % e)
        return 3
    for b in bad:
        print("FAIL " + b)
    if not bad:
        print("ok   the companion's list is what %s names: %d names, %d starts" % (DOC, len(names), len(starts)))
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
