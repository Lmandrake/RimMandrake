		private static bool Near(float a, float b, float eps = 1e-4f) => Math.Abs(a - b) < eps;

		public static void Run(Action<string, Action> Case)
		{
			// RIMMANDRAKE_FIX_PIT_FLOOR_TINT_PAST_TWO_M_DRAWS_ONE_COLOUR: the shade must DRAW the law. Over the live deep floor (about 34 of
			// 255) a (10, 8, 7) tint drew 16 m at 0.535 of the 2 m floor against the law's 0.34 (ArchBig, 2026-11-22).
			Case("PitRelief_floor_shade_draws_the_brightness_law", () =>
			{
				// every floor past 2 m is one terrain (t); the shade draws each against the 2 m floor's own draw, as the law says
				float t = 34f / 255f, two = RM_PitReliefMath.FloorBrightness(4), drawnTwo = RM_PitReliefMath.FloorDrawn(t, 4);
				for (int d = 4; d <= 64; d++)
				{
					float drawn = RM_PitReliefMath.FloorDrawn(t, d) / drawnTwo, law = RM_PitReliefMath.FloorBrightness(d) / two;
					Assert(Math.Abs(drawn - law) < 0.005f, "can-fail: a " + (d * 0.5f) + " m floor draws at " + drawn + " of the 2 m floor, the law says " + law);
				}
				Assert(RM_PitReliefMath.FloorDrawn(t, 16) <= 0.9f * RM_PitReliefMath.FloorDrawn(t, 8), "can-fail: 8 m draws a tenth darker than 4 m");
			});
			Case("PitRelief_floor_shade_and_face_foot_match_the_model", () =>
			{
				Assert(FloorGolden.GetLength(0) > 40 && FootGolden.GetLength(0) > 10, "can-fail: the golden tables are filled");
				for (int i = 0; i < FloorGolden.GetLength(0); i++)
				{
					float a = RM_PitReliefMath.FloorShade((int)FloorGolden[i, 0]);
					Assert(Near(a, FloorGolden[i, 1]), "can-fail: FloorShade(" + FloorGolden[i, 0] + ") = " + a + ", model " + FloorGolden[i, 1]);
				}
				for (int i = 0; i < FootGolden.GetLength(0); i++)
				{
					float a = RM_PitReliefMath.FaceFootShade(FootGolden[i, 0]);
					Assert(Near(a, FootGolden[i, 1]), "can-fail: FaceFootShade(" + FootGolden[i, 0] + ") = " + a + ", model " + FootGolden[i, 1]);
				}
			});
			Case("PitRelief_corners_match_the_model", () =>
			{
				Assert(CornerGolden.GetLength(0) > 20, "can-fail: the corner table is filled");
				for (int i = 0; i < CornerGolden.GetLength(0); i++)
				{
					int d = (int)CornerGolden[i, 0], dn = (int)CornerGolden[i, 1], ds = (int)CornerGolden[i, 2], dd = (int)CornerGolden[i, 3];
					bool has = RM_PitReliefMath.CornerPiece(d, dn, ds, dd, CornerGolden[i, 4], out float w, out float h);
					Assert(has == (CornerGolden[i, 5] > 0f) && Near(w, CornerGolden[i, 5]) && Near(h, CornerGolden[i, 6]),
						"can-fail: CornerPiece(" + d + "," + dn + "," + ds + "," + dd + "," + CornerGolden[i, 4] + ") = " + has + " " + w + "x" + h
						+ ", model " + CornerGolden[i, 5] + "x" + CornerGolden[i, 6]);
					bool closes = RM_PitReliefMath.ClosesCorner(d, dn, ds, dd);
					Assert(closes == (CornerGolden[i, 7] > 0f), "can-fail: ClosesCorner(" + d + "," + dn + "," + ds + "," + dd + ") = " + closes);
				}
				float[] xz = new float[8];
				RM_PitReliefMath.CornerPoly(false, 0.17f, 0.35f, xz);
				Assert(Near(xz[0], 0f) && Near(xz[1], 0.65f) && Near(xz[6], 0.17f) && Near(xz[7], 0.82f), "can-fail: the west corner piece's mitred foot");
				RM_PitReliefMath.CornerPoly(true, 0.17f, 0.35f, xz);
				Assert(Near(xz[0], 0.83f) && Near(xz[1], 0.82f) && Near(xz[6], 1f) && Near(xz[7], 0.65f), "can-fail: the east corner piece's mitred foot");
			});
			Case("PitRelief_floor_rects_and_drowned_parts_match_the_model", () =>
			{
				Assert(RectGolden.GetLength(0) > 10, "can-fail: the rect table is filled");
				float[] r = new float[8];
				for (int i = 0; i < RectGolden.GetLength(0); i++)
				{
					Array.Clear(r, 0, 8);
					int n = RM_PitReliefMath.FloorRects(RectGolden[i, 0], RectGolden[i, 1], RectGolden[i, 2], RectGolden[i, 3], RectGolden[i, 4],
						RectGolden[i, 5], RectGolden[i, 6], r);
					Assert(n == (int)RectGolden[i, 7], "can-fail: FloorRects row " + i + " count " + n + ", model " + RectGolden[i, 7]);
					for (int k = 0; k < 4 * n; k++)
					{
						Assert(Near(r[k], RectGolden[i, 8 + k]), "can-fail: FloorRects row " + i + " value " + k + " = " + r[k] + ", model " + RectGolden[i, 8 + k]);
					}
				}
			});
			Case("PitRelief_redraw_and_concealment_rules", () =>
			{
				for (int b = 0; b <= 44; b++)
				{
					for (int a = 0; a <= 44; a++)
					{
						Assert(RM_PitReliefMath.RedrawsOnDepthChange(b, a) == (a != b), "can-fail: a change " + b + " -> " + a + " redraws");
					}
				}
				Assert(!RM_PitReliefMath.DrawsPitArt(0, false, false), "can-fail: undug draws nothing");
				Assert(RM_PitReliefMath.DrawsPitArt(4, false, false), "can-fail: an open pit draws");
