#!/usr/bin/env python3
"""REEL_TAP_CAMERA_REDRAW_STILL_SIDE_ON: before/after composites. Each reel look x state: rows west/north/south, columns
before and after at 32 px/cell (play zoom) and 128 px/cell (4x), on ground with the 2x2 footprint outlined and a laid hose
whose end coupling sits on the outlet tip reel_intake_geometry.measure() finds in THAT picture (the same rule the game's
ReelIntakeGeometry table is generated by), leaving the way the hose leaves (west/north/south). Plus the bleed well.
usage: composites.py <candidates dir (holds Hose/ and Machinery/)> <out dir>"""
import os
import sys
from PIL import Image, ImageDraw

REPO = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "..", ".."))
sys.path.insert(0, os.path.join(REPO, "src", "RimMandrake", "Utils", "mockups", "messy_conduit"))
import reel_intake_geometry as rig  # noqa: E402

HOSE = os.path.join(REPO, "src", "RimMandrake", "FlowWorks", "Textures", "RimMandrake", "FlowWorks", "Hose")
TAP = os.path.join(REPO, "src", "RimMandrake", "FlowWorks", "Textures", "Things", "Building", "FlowWorks", "Machinery", "RM_LiquidTap.png")
LOOKS = [("Scrapper", ""), ("Industrial", "Styles/Industrial/"), ("Modern", "Styles/Modern/"), ("Futuristic", "Styles/Futuristic/")]
FR = [("west", "", 0), ("north", "_north", 1), ("south", "_south", -1)]
GROUND, GRID, FOOT = (118, 98, 70, 255), (100, 82, 58, 255), (235, 210, 90, 255)
HOSE_C, COUP = (60, 52, 44, 255), (190, 150, 70, 255)
DRAW = 2.15


def tip_in_picture(path, k):
    _inlet, _out, tip = rig.measure(path, k)
    dx, dz = tip
    if k == 1:
        return (dz, -dx), (0, 1)      # art west -> picture north
    if k == -1:
        return (-dz, dx), (0, -1)     # art west -> picture south
    return (dx, dz), (-1, 0)


def tile(art, p, cells, foot, hose=None, label=""):
    n = int(cells * p)
    im = Image.new("RGBA", (n, n + 14), (40, 34, 28, 255))
    g = Image.new("RGBA", (n, n), GROUND)
    d = ImageDraw.Draw(g)
    for i in range(int(cells) + 1):
        d.line([(i * p, 0), (i * p, n)], fill=GRID)
        d.line([(0, i * p), (n, i * p)], fill=GRID)
    c = n / 2
    d.rectangle([c - foot / 2 * p, c - foot / 2 * p, c + foot / 2 * p, c + foot / 2 * p], outline=FOOT, width=max(1, p // 32))
    if hose:
        (tx, tz), (ux, uz) = hose
        x0, y0 = c + tx * p, c - tz * p
        x1, y1 = x0 + ux * 1.6 * p, y0 - uz * 1.6 * p
        d.line([(x0, y0), (x1, y1)], fill=HOSE_C, width=max(2, int(0.16 * p)))
        # the hose's end coupling: a short collar whose face sits ON the measured outlet tip, the hose running away from it
        cl, cr = 0.14 * p, 0.10 * p
        ex, ey = x0 + ux * cl, y0 - uz * cl
        if ux:
            d.rectangle([min(x0, ex), y0 - cr, max(x0, ex), y0 + cr], fill=COUP, outline=(90, 70, 30, 255))
        else:
            d.rectangle([x0 - cr, min(y0, ey), x0 + cr, max(y0, ey)], fill=COUP, outline=(90, 70, 30, 255))
    a = Image.open(art).convert("RGBA").resize((int(DRAW * p if foot == 2 else 1 * p),) * 2, Image.LANCZOS)
    g.alpha_composite(a, (int(c - a.width / 2), int(c - a.height / 2)))
    if hose:   # a red tick on the measured tip, drawn over the art so the reader sees where the coupling must meet
        d2 = ImageDraw.Draw(g)
        d2.ellipse([x0 - 2, y0 - 2, x0 + 2, y0 + 2], outline=(255, 40, 40, 255))
    im.alpha_composite(g, (0, 14))
    ImageDraw.Draw(im).text((2, 1), label, fill=(240, 230, 210, 255))
    return im


def row(imgs, gap=6):
    w = sum(i.width for i in imgs) + gap * (len(imgs) - 1)
    h = max(i.height for i in imgs)
    out = Image.new("RGBA", (w, h), (40, 34, 28, 255))
    x = 0
    for i in imgs:
        out.alpha_composite(i, (x, 0))
        x += i.width + gap
    return out


def col(imgs, gap=6):
    w = max(i.width for i in imgs)
    h = sum(i.height for i in imgs) + gap * (len(imgs) - 1)
    out = Image.new("RGBA", (w, h), (40, 34, 28, 255))
    y = 0
    for i in imgs:
        out.alpha_composite(i, (0, y))
        y += i.height + gap
    return out


def main(cand, out):
    os.makedirs(out, exist_ok=True)
    made = []
    for look, folder in LOOKS:
        for art, st in (("Reel_PumpHookup", "stored"), ("Reel_Deployed", "laid")):
            rows = []
            for fname, suf, k in FR:
                b = os.path.join(HOSE, folder + art + suf + ".png")
                a = os.path.join(cand, "Hose", folder + art + suf + ".png")
                hb, ha = tip_in_picture(b, k), tip_in_picture(a, k)
                rows.append(row([tile(b, 32, 6, 2, hb, "before %s 32" % fname), tile(a, 32, 6, 2, ha, "after %s 32" % fname),
                                 tile(b, 128, 4, 2, hb, "before %s 128px/cell" % fname), tile(a, 128, 4, 2, ha, "after %s 128px/cell" % fname)]))
            p = os.path.join(out, "%s_%s.png" % (look, st))
            col(rows).save(p)
            made.append(p)
    p = os.path.join(out, "RM_LiquidTap.png")
    a = os.path.join(cand, "Machinery", "RM_LiquidTap.png")
    row([tile(TAP, 32, 3, 1, None, "before 32"), tile(a, 32, 3, 1, None, "after 32"),
         tile(TAP, 128, 2, 1, None, "before 128"), tile(a, 128, 2, 1, None, "after 128")]).save(p)
    made.append(p)
    print("\n".join(made))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
