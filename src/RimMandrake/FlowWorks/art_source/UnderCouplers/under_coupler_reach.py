#!/usr/bin/env python3
"""How far each hose under-coupler's pipe runs: to the first OPAQUE BODY run of the fixture's art, never across open ground.

Naive-judge FIX 2026-10-23 (infrastructure/state/delegated/2026-10-23/under_couplers.json): run to the footprint's centre line,
the south and west pipes of the Modern tall/XTall tanks (no base plate) met in a bare T on open ground beside the body. So the
pipe stops beneath the art: walking inward from the port point along the pipe's axis, the first place where the fixture's art
is opaque (alpha > 128) across the WHOLE pipe width and stays so for RUN cells; the pipe ends OVERLAP cells past that
point (under the body), never beyond the footprint centre line. No such run before the centre line (+ SEARCH_PAST) =
NO_BODY (-1): the C# draws no under-coupler there (the hose's old stub path), and the gate lists the port as a known red.

Measured for every hose-coupling building x look x side x lane the gate knows (selftest_hose_fittings.ports(); lane = the
end cell's index along the side, from the port point: floor of its along-side offset), at the def's drawSize/drawOffset.
  python3 under_coupler_reach.py           check Source/Machinery/UnderCouplerReach.cs is what it would generate (exit 1)
  python3 under_coupler_reach.py --write   regenerate it
"""
import math
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
FW = os.path.abspath(os.path.join(HERE, "..", ".."))
sys.path.insert(0, FW)
import selftest_hose_fittings as gate  # noqa: E402  (defs, ports, art loader, UnderCouplerGeometry constants)

OUT = os.path.join(FW, "Source", "Machinery", "UnderCouplerReach.cs")
RUN, OVERLAP, SEARCH_PAST = 0.12, 0.08, 0.3
NO_BODY = -1.0
SIDE_INDEX = {"south": 0, "north": 1, "west": 2, "east": 3}   # by the unit step end cell -> fixture: (0,1) (0,-1) (1,0) (-1,0)


def lane_of(b, side, pt):
    along = pt[0] if side in ("north", "south") else pt[1]
    n = b["size"][0] if side in ("north", "south") else b["size"][1]
    return max(0, min(n - 1, int(math.floor(along))))


def reach(fix, step, pt, side, size, geo):
    """The clipped reach (cell from the port point), or NO_BODY."""
    nx, nz = gate.SIDES[side]
    tx, tz = -nz, nx
    full = gate.reach_of(pt, side, size, geo)
    pw = geo[2]
    d, first = step / 2.0, None
    while d < full + SEARCH_PAST:
        if all(fix(pt[0] + tx * t - nx * d, pt[1] + tz * t - nz * d) for t in np.linspace(-pw / 2, pw / 2, 7)):
            if first is None:
                first = d
            if d - first >= RUN:
                break
        else:
            first = None
        d += step
    if first is None or d - first < RUN or first > full:
        return NO_BODY
    return round(max(geo[0], min(full, first + OVERLAP)), 3)


def table():
    """[(def, look key, side index, lane, reach)] -- look key "" for a def with no looks."""
    dz, geo = gate.port_dz_table(), gate.under_geom()
    rows = []
    for b in sorted(gate.load_defs(), key=lambda x: x["def"]):
        for look, g in b["looks"].items():
            if g["graphicClass"] not in (None, "Graphic_Single"):
                continue
            a, _ = gate.load_alpha(g["texPath"])
            if a is None:
                continue
            fix, step = gate.fixture_opaque(a, g, b["size"])
            for side, lane, pt in gate.ports(b, look, dz):
                rows.append((b["def"], "" if look not in gate.LOOKS else look, SIDE_INDEX[side], lane_of(b, side, pt),
                             reach(fix, step, pt, side, b["size"], geo)))
    return rows


def render(rows):
    body = "\n".join('            { "%s|%s|%d|%d", %.3f },' % r for r in rows)
    return '''// GENERATED by FlowWorks/art_source/UnderCouplers/under_coupler_reach.py --write from the installed fixture art; do not edit.
// Verse-free. Naive-judge FIX 2026-10-23: an under-coupler's pipe ends beneath the first opaque body run, never on open ground.
using System.Collections.Generic;

namespace RimMandrake.FlowWorks.Machinery
{
    /// <summary>Per fixture def | look ("" = no looks) | side (0 south, 1 north, 2 west, 3 east: the end cell's side of the
    /// fixture) | lane (the end cell's index along that side): how far the under-coupler's pipe runs from the port point,
    /// cells; -1 = the art has no opaque body on that axis (no under-coupler there). Unmeasured fixtures are absent.</summary>
    public static class UnderCouplerReach
    {
        public const double NoBody = -1.0;

        private static readonly Dictionary<string, double> Table = new Dictionary<string, double>
        {
%s
        };

        /// <summary>The measured reach, or false (an unmeasured fixture: the caller keeps the geometric reach).</summary>
        public static bool TryGet(string def, string look, int side, int lane, out double reach) =>
            Table.TryGetValue(def + "|" + (look ?? "") + "|" + side + "|" + lane, out reach);
    }
}
''' % body


def main():
    want = render(table())
    if "--write" in sys.argv:
        open(OUT, "w", newline="\n").write(want)
        print("wrote", os.path.relpath(OUT, gate.REPO))
        return 0
    have = open(OUT).read() if os.path.exists(OUT) else ""
    ok = have == want
    print(("ok    " if ok else "FAIL  ") + "UnderCouplerReach.cs matches the installed art (%d ports)" % want.count("\n            {"))
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
