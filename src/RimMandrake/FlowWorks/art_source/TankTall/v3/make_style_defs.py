"""TANK_TALL_BUILD_TWICE_THE_DRINK v3: write RM_LiquidTankStyles.xml - one ThingStyleDef per tank x look (the four Gimme Some
Slack looks), named <Tank>_<Look> (PipeStyles.StyleDefName), texPath RimMandrake/FlowWorks/Tank/<Look>/<Tank>
(PipeStyles.TankTexPath), drawSize/drawOffset copied from the tank's own ThingDef so a style never moves the drawing.
Installed 2026-10-15: this file is written into Defs/LiquidTypes/ThingDefs/ and the 16 PNGs went into
Textures/RimMandrake/FlowWorks/Tank/<Look>/ by install_looks.py (art ledger). usage: make_style_defs.py <out.xml>"""
import sys
import xml.etree.ElementTree as ET
from pathlib import Path
FW = Path(__file__).resolve().parents[3]
LOOKS = ["Scrapper", "Industrial", "Modern", "Futuristic"]
SRC = {"RM_LiquidTank": "LiquidTypes/ThingDefs/RM_LiquidTank.xml", "RM_LiquidTankTall": "LiquidTypes/ThingDefs/RM_LiquidTank.xml",
       "RM_UniversalCargoTank": "Machinery/RM_LiquidLogistics.xml", "RM_UniversalCargoTankXTall": "Machinery/RM_LiquidLogistics.xml"}
out = ['<?xml version="1.0" encoding="utf-8"?>',
       '<!-- The four liquid tanks\' four looks (owner 2026-10-14, TANK_TALL_BUILD_TWICE_THE_DRINK: "They should have the same four',
       '     variant styles as Gimme Some Slack."). Generated by art_source/TankTall/v3/make_style_defs.py; picked on the build button',
       '     through the shared style picker (Machinery/PipeLook.cs registers PipeStyles.TankDefs once these load). No StyleCategoryDef',
       '     lists these, so no ideoligion can hand them out. Art: the measured building camera,',
       '     design/RimMandrake/building_camera_perspective_2026-10-14.md. -->', '<Defs>']
for tank, rel in SRC.items():
    root = ET.parse(FW / "Defs" / rel).getroot()
    td = next(t for t in root.iter("ThingDef") if t.findtext("defName") == tank)
    g = td.find("graphicData")
    ds, off = g.findtext("drawSize"), g.findtext("drawOffset")
    for look in LOOKS:
        out += ["", "  <ThingStyleDef>", f"    <defName>{tank}_{look}</defName>", f"    <label>{look.lower()}</label>",
                "    <graphicData>", f"      <texPath>RimMandrake/FlowWorks/Tank/{look}/{tank}</texPath>",
                "      <graphicClass>Graphic_Single</graphicClass>", f"      <drawSize>{ds}</drawSize>"]
        if off:
            out.append(f"      <drawOffset>{off}</drawOffset>")
        out += ["    </graphicData>", "  </ThingStyleDef>"]
out += ["", "</Defs>", ""]
Path(sys.argv[1]).write_text("\n".join(out), encoding="utf-8")
print(sys.argv[1], 4 * len(SRC), "style defs")
