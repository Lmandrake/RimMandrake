#!/usr/bin/env python3
"""Stake library for the pit spikes (PIT_SPIKES_FIX_OVER_WALL_AND_SUBMERGE): writes Source/Superdeep/RM_SpikeStakes.cs.

Owner 2026-10-24: "you can see the spi[k]es aren't right. They should not be showing drawn over the paler walls, right? And
I needed deeper water to test the spikes. They should be shown as submerged rapidly."

The shipped art (Textures/.../Canals/RM_Spikes/RM_Spikes_{a,b,c}.png, owner-accepted 2026-10-21) is a field of separate
stakes drawn over the whole cell at Building altitude, so it covers the pit's far-wall face, side bevels and outline
(RM_ExcavationWalls, TerrainScatter altitude). The fix keeps the owner's stakes but lays them out at draw time
(RM_SpikeDrawMath.Layout) inside the floor the walls leave visible. This script cuts each variant's ISOLATED stakes (an
8-connected alpha component no taller than MAX_STAKE_PX; overlapping stakes merge into tall chains and are not used)
into a UV library, and measures the variant's density (stakes per cell^2 = opaque area / mean stake area) so the layout
keeps the original's look. Units: cells (256 px = 1 cell at drawSize 1); UV is Unity's (v up).

    python3 stakes.py            # (re)writes RM_SpikeStakes.cs
    python3 stakes.py --check    # exit 1 if the .cs on disk is not what this script writes (the offline selftest runs it)
"""
import math
import sys
from pathlib import Path

import numpy as np
from PIL import Image

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from label import boxes  # noqa: E402

FW = HERE.parents[1]
TEX = FW / "Textures/Things/Building/FlowWorks/Canals/RM_Spikes"
OUT = FW / "Source/Superdeep/RM_SpikeStakes.cs"
VARIANTS = "abc"
MAX_STAKE_PX = 52        # a single stake is 34..47 px tall; the shortest merged chain is 60 px (variant a), so this splits them
PAD = 1                  # px of anti-aliased fringe kept round each stake's box


def library(variant):
    """(stakes, (pitch_x, pitch_z)): stakes = [(w, h, u0, v0, u1, v1)] in cells / Unity UV, in scan order."""
    im = Image.open(TEX / ("RM_Spikes_%s.png" % variant)).convert("RGBA")
    a = np.asarray(im)[..., 3]
    S = a.shape[0]
    out, areas = [], []
    for x0, y0, x1, y1 in boxes(a > 0):
        if y1 - y0 + 1 > MAX_STAKE_PX:
            continue
        areas.append(int((a[y0:y1 + 1, x0:x1 + 1] > 0).sum()))
        x0, y0, x1, y1 = max(0, x0 - PAD), max(0, y0 - PAD), min(S - 1, x1 + PAD), min(S - 1, y1 + PAD)
        out.append(((x1 - x0 + 1) / S, (y1 - y0 + 1) / S, x0 / S, 1 - (y1 + 1) / S, (x1 + 1) / S, 1 - y0 / S))
    assert areas, "variant %s: no isolated stake under %d px" % (variant, MAX_STAKE_PX)
    ys, xs = np.nonzero(a > 0)
    field = (xs.max() - xs.min() + 1) * (ys.max() - ys.min() + 1)
    per_cell2 = (a > 0).sum() / np.mean(areas) / field * S * S
    pitch = 1 / math.sqrt(per_cell2)
    return out, (pitch, pitch)


def render():
    f = lambda v: "%.6ff" % v
    lines = [
        "// GENERATED by FlowWorks/art_source/Spikes/stakes.py from Textures/Things/Building/FlowWorks/Canals/RM_Spikes/ -- do not",
        "// edit; re-run the script (the offline selftest fails while this file and the PNGs disagree).",
        "namespace RimMandrake.FlowWorks",
        "{",
        "\t/// <summary>PIT_SPIKES_FIX_OVER_WALL_AND_SUBMERGE: each spike variant's isolated stakes as UV boxes (w, h in cells; u0, v0, u1, v1",
        "\t/// Unity UV) and the grid pitch (cells) that keeps the variant's stake density. Verse-free.</summary>",
        "\tpublic static class RM_SpikeStakes",
        "\t{",
        "\t\tpublic const string Variants = \"%s\";" % VARIANTS,
    ]
    libs, pitches = [], []
    for v in VARIANTS:
        st, (px, pz) = library(v)
        libs.append("\t\t\tnew float[] {\n" + ",\n".join("\t\t\t\t" + ", ".join(f(q) for q in s) for s in st) + " },")
        pitches.append("\t\t\t{ %s, %s }," % (f(px), f(pz)))
    lines += ["\t\tpublic static readonly float[][] Stakes =", "\t\t{"] + libs + ["\t\t};",
              "\t\tpublic static readonly float[,] Pitch =", "\t\t{"] + pitches + ["\t\t};", "\t\tpublic const int Stride = 6;", "\t}", "}", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        ok = OUT.exists() and OUT.read_text() == text
        print("RM_SpikeStakes.cs is current" if ok else "RM_SpikeStakes.cs is STALE: re-run stakes.py")
        sys.exit(0 if ok else 1)
    OUT.write_text(text)
    for v in VARIANTS:
        st, p = library(v)
        print(v, len(st), "stakes, pitch %.3f cell" % p[0])
