#!/usr/bin/env python3
"""Writes Defs/Layouts/RM_Layouts.xml, the two KCSG layouts of BESKAR_ARMORER_QUEST_1. Hand-drawn ASCII here, so the art of the
place is reviewable as a picture instead of as comma grids. Run it after editing a picture; commit both. Legend below."""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "Defs", "Layouts", "RM_Layouts.xml")
SYM = {".": ".", "W": "Wall_Steel", "D": "Autodoor_Steel", "F": "RM_Symbol_ArmorerForge", "B": "Bed_Steel", "S": "Shelf_Steel", "#": "."}
# space: open floor with no roof; everything else is roofed
COVERT = [
    "WWWWWWWWWWWWWWWWWW###",
    "W......W.........W###",
    "W.B....W....F....W###",
    "W......W.........W###",
    "W......W.........D###",
    "W.B....W.........W###",
    "W......D.........W###",
    "W.B....W.........D###",
    "W......W.........W###",
    "WWWDWWWWWWWDWWWWWW###",
    "#####################",
    "#####################",
]
POST = [
    "WWWWWWWWWWWWWWWWWWWW",
    "WB.WB.WB.WB.W......W",
    "W..W..W..W..W......W",
    "WWDWWDWWDWWDW..S...W",
    "W..................W",
    "W..................W",
    "WWWWWWWWWDWWWWWWWWWW",
    "W.........W.......W#",
    "W.........D.......W#",
    "WWWWDWWWWWWWWWWWWWW#",
]


def grid(rows, f):
    return "\n".join("      <li>%s</li>" % ",".join(f(c) for c in r) for r in reversed(rows))


def layout(name, rows, floor, under):
    terrain = grid(rows, lambda c: floor if c != "#" else under)
    roof = grid(rows, lambda c: "1" if c in ".BSDFW" else "0")
    things = "\n".join("        <li>%s</li>" % ",".join(SYM[c] for c in r) for r in reversed(rows))
    return """  <KCSG.StructureLayoutDef>
    <defName>%s</defName>
    <spawnConduits>false</spawnConduits>
    <forceGenerateRoof>true</forceGenerateRoof>
    <terrainGrid>
%s
    </terrainGrid>
    <roofGrid>
%s
    </roofGrid>
    <layouts>
      <li>
%s
      </li>
    </layouts>
  </KCSG.StructureLayoutDef>
""" % (name, terrain, roof, things)


def main():
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as f:
        f.write('<?xml version="1.0" encoding="utf-8"?>\n<!-- GENERATED by Source/gen_layouts.py. -->\n<Defs>\n')
        f.write(layout("RM_ArmorerCovertLayout", COVERT, "OrbitalPlatform", "OrbitalPlatform"))
        f.write(layout("RM_ImperialDetentionPostLayout", POST, "Concrete", "Concrete"))
        f.write("</Defs>\n")


if __name__ == "__main__":
    main()
