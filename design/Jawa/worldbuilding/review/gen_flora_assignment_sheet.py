def mature_cells(row: dict):
    dx, vmax = row.get("drawSizeX"), row.get("visualSizeMax")
    if dx is None or vmax is None:
        return None
    return float(dx) * float(vmax)


def plant_shape(row: dict) -> str:
    if row.get("isTree"):
        return "a tree"
    size = row.get("visualSizeMax")
    if isinstance(size, (int, float)) and size >= 0.9:
        return "a bush"
    if row.get("cavePlant"):
        return "cave growth"
    return "ground cover"


def plant_bits(row: dict, comm) -> str:
    bits = [plant_shape(row)]
    cells = mature_cells(row)
    if cells is not None:
        bits.append(f"{F.num(cells)} squares on screen when grown (a person is 1.5)")
    if row.get("growDays"):
        bits.append(f"grows in {F.num(row['growDays'])} days")
    if row.get("cavePlant"):
        bits.append("cave-only")
    if str(row.get("pollution") or "").lower() not in ("", "any", "none"):
        bits.append(f"pollution: {row['pollution']}")
    product = row.get("product")
    if isinstance(product, dict) and (product.get("label") or product.get("defName")):
        bits.append(f"yields {product.get('label') or product['defName']}")
    if comm is not None:
        bits.append(F.rarity_phrase(comm))
    return " · ".join(bits)


def art_prefills() -> dict[str, str]:
    out = {}
    try:
        doc = json.loads(PLANT_ART_DECISIONS.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return out
    for defname, rec in (doc.get("decisions") or {}).items():
        v = ART_MAP.get(rec.get("decision") or "")
        if v:
            out[defname] = v
    return out


def slugify(text: str) -> str:
    return re.sub(r"-{2,}", "-", re.sub(r"[^a-z0-9]+", "-", str(text).lower())).strip("-")[:60]


def build_items(sheets, plants, panels):
    art_pre = art_prefills()
    cards, flora_rows, ledger_p, ledger_o = [], [], [], []

    for card in CARDS:
        cards.append({
            "id": card["id"], "label": card["label"], "group": CARD_GROUP,
            "thumb": None, "effect": card["q"],
            "card": {"q": card["q"], "trade": card["trade"], "rec": card["rec"]},
            "prefill": card["prefill"], "contested": True,
            "hasSize": False, "hasArt": False,
        })

    for doc in sheets:
        key = doc["sheet"]
        tiles = doc.get("tiles")
        gname = F.pretty_sheet(key) + (f" — {tiles:,} tiles" if isinstance(tiles, int) else "")
        own_defs = set(doc.get("defNames") or [])

        for entry in doc.get("flora") or []:
            defname = entry["def"]
            row = plants.get(defname) or {}
            cells = mature_cells(row)
            mbin = F.size_bin(cells)
            law = entry.get("law") or ""
            note = entry.get("note") or ""
            sentences = []
            if law:
                sentences.append("Why it's here: " + F.plain(law))
            if note:
                sentences.append(F.plain(note))
            interim = bool(re.search(r"interim|stand-in|placeholder", f"{law} {note}", re.I))
            if interim:
                sentences.append("This one is a stand-in: the plant the biome "
                                 "really wants is on the new-art list below, and "
                                 "this is the best available body until it exists.")
            zeroed = any(b.get("biomeDef") in own_defs
                         for b in (row.get("zeroedBiomes") or []))
            if zeroed:
                sentences.append("Heads-up: an old content cut still blocks this "
                                 "plant from growing here — it gets lifted when "
                                 "this row lands as In.")
            pan = (panels.get(defname) or {})
            item = {
                "id": f"flora:{key}:{defname}",
                "label": row.get("label") or defname,
                "group": gname,
                "thumb": (row.get("art") or {}).get("detail"),
                "effect": plant_bits(row, entry.get("commonality")),
                "sentences": sentences,
                "modLine": F.mod_line(row.get("mod") or ""),
                "badge": F.mod_badge(row.get("mod") or ""),
                "prefill": "in",
                "contested": interim,
                "cells": cells,
                "sizeBinPrefill": mbin or "",
                "sizeMeans": ("keeps its current size." if mbin else
                              "I could not measure its grown size."),
                "hasSize": mbin is not None,
                "hasArt": True,
            }
            if art_pre.get(defname):
                item["artPrefill"], item["artSrc"] = art_pre[defname], (
                    "the plant register's grading")
            else:
                ppc = (row.get("art") or {}).get("pxPerCell")
                if ppc is not None and ppc < 0.7:
                    item["artPrefill"], item["artSrc"] = "improve", (
                        "the sprite is blurry at the size the game draws it")
                else:
                    item["artPrefill"], item["artSrc"] = "keep", "no visible defect"
            if pan.get("file"):
                item["panel"] = {"file": pan["file"], "w": pan["w"], "h": pan["h"],
                                 "shown": pan.get("shownPct") or 100}
            else:
                item["sentences"].append("I could not render this one to scale — "
                                         "the small picture is NOT at true size.")
            flora_rows.append(item)

        # ── the NEW ART/DEF ledger ────────────────────────────────────────────
        seen_slugs: dict[str, int] = {}
        for new in doc.get("new_defs") or []:
            kind = (new.get("kind") or "?").lower()
            name = new.get("name") or "(unnamed)"
            slug = slugify(name) or "unnamed"
            n = seen_slugs.get(slug, 0)
            seen_slugs[slug] = n + 1
            if n:
                slug = f"{slug}-{n+1}"
            load = new.get("mechanic_load") or "none"
            needs_code = load and load != "none"
            eff = (f"A new {kind} to create for {F.pretty_sheet(key)}"
                   + (" — needs new game code too: " + F.plain(load) if needs_code
                      else " — art and a definition only, no new code"))
            ledger = ledger_p if kind == "plant" else ledger_o
            ledger.append({
                "id": f"ledger:{key}:{slug}",
                "label": " ".join(str(name).split()[:12]),
                "group": LEDGER_PLANTS if kind == "plant" else LEDGER_OTHER,
                "thumb": None,
                "effect": eff,
                "sentences": [("Asked for by the biome's own design sheet. In "
                               "commissions it as a drawing/def job; Out drops it "
                               "and the biome stays thin there for good.")],
                "prefill": "in",
                "hasSize": False, "hasArt": False,
            })

    flora_rows.sort(key=lambda it: (it["group"],
                                    it["cells"] if it["cells"] is not None else 99,
                                    it["label"].lower()))
    ledger_p.sort(key=lambda it: it["group"] + it["label"].lower())
    ledger_o.sort(key=lambda it: it["group"] + it["label"].lower())
    items = cards + flora_rows + ledger_p + ledger_o
    F.scale_groups(items)

    counts = {
        "rows": len(items),
        "cards": len(cards),
        "flora": len(flora_rows),
        "ledger": len(ledger_p) + len(ledger_o),
        "biomes": len({it["group"] for it in flora_rows}),
        "contested": sum(1 for it in items if it.get("contested")),
        "panels": sum(1 for it in items if it.get("panelSrc")),
    }
    return items, counts


