def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--sheet-only", action="store_true")
    ap.add_argument("--i-know-this-overwrites-the-owners-decisions",
                    action="store_true", dest="force")
    ap.add_argument("--template")
    args = ap.parse_args()
    if args.template:
        F.TEMPLATE_CANDIDATES.insert(0, pathlib.Path(args.template))

    sheets, _glob = F.read_rosters()
    plants = {r["defName"]: r
              for r in json.loads(PLANT_REGISTER.read_text(encoding="utf-8"))["rows"]}
    panels = json.loads(PANELS.read_text(encoding="utf-8"))["panels"]
    items, counts = build_items(sheets, plants, panels)

    for it in items:
        if it.get("thumb") and not (HERE / it["thumb"]).is_file():
            it["thumb"] = None

    config = {
        "sheetId": "flora_assignment_register",
        "title": "Flora of Ash'karr — what grows where",
        "subtitle": f"{counts['flora']} plants in {counts['biomes']} biomes · "
                    f"{counts['ledger']} new things to create · "
                    f"{counts['cards']} question",
        "briefHtml": brief_html(counts),
        "criterion": CRITERION,
        "invented": INVENTED,
        "posture": {
            "mode": "blacklist",
            "explain": "Everything stands as recommended unless you overrule it. "
                       "Plant rows are already-landed data; a new-things row's In "
                       "commissions it, Out drops it for good.",
        },
        "options": [
            {"key": "in",    "label": "In",           "hotkey": "1", "color": "#5ac37f", "counts": "in"},
            {"key": "move",  "label": "Move",         "hotkey": "2", "color": "#6aa6e8", "counts": "in"},
            {"key": "out",   "label": "Out",          "hotkey": "3", "color": "#e06c6c", "counts": "out"},
            {"key": "later", "label": "Decide later", "hotkey": "4", "color": "#98a2b3"},
        ],
        "groupLabel": "section",
        "media": True,
        "decisionsFile": DECISIONS.name,
        "decisionsPath": NATIVE_DIR + "\\" + DECISIONS.name,
        "sheetPath": NATIVE_DIR + "\\" + SHEET.name,
    }

    SHEET.write_text(F.fill(F.load_template(), config, items), encoding="utf-8")
    print(f"wrote {SHEET.name}: {counts}")

    if args.sheet_only:
        return 0
    F.guard_decisions(DECISIONS, args.force)
    doc = {
        "sheet": "flora_assignment_register",
        "posture": "blacklist",
        "postureMeaning": "Stands as recommended unless overruled. In on a "
                          "new-things row commissions it; Out drops it for good.",
        "criterion": CRITERION,
        "generatedBy": "gen_flora_assignment_sheet.py (2026-09-09 rulings rebuild)",
        "generatedFrom": "design/Jawa/worldbuilding/biomes/rosters/*.json",
        "invented": INVENTED,
        "decisions": {
            it["id"]: {
                "decision": it["prefill"],
                "prefill": it["prefill"],
                "note": it.get("openNote") or "",
                **({"sizeBin": it["sizeBinPrefill"],
                    "sizeBinPrefill": it["sizeBinPrefill"]} if it.get("hasSize") else {}),
                **({"art": it["artPrefill"],
                    "artPrefill": it["artPrefill"]} if it.get("hasArt") else {}),
            }
            for it in items
        },
    }
    DECISIONS.write_text(json.dumps(doc, indent=1, ensure_ascii=False) + "\n",
                         encoding="utf-8")
    print(f"wrote {DECISIONS.name} ({len(doc['decisions'])} pre-filled rows)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
